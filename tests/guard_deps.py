#!/usr/bin/env python3
"""Guard D and I: module dependency map and direction rule.
Source of truth for the order: src/manifest.json (JS files only). Edges per file:
  import   `import ... from "./x.js"` between files of the same folder (explicit)
  global   an identifier the file reads that exactly ONE other file defines at top level (function/const/let/var/class/export, window.NAME=, __R.NAME / defineProperty(__R,"NAME"));
           names shorter than 4 characters and names defined by several files are skipped (ambiguous). Local shadowing can cause a rare false edge, the baseline absorbs it.
Layers (tests/guard_lib.py layer()): data(0) = src/data and *-data-* files, logic(1) = *-logic-*, engine, sim, UI(2) = *-ui-*, src/fx. reg, main, boot, env and bridge files are unclassified and exempt.
Rule: data may not read logic or UI, logic may not read UI. A back-edge = an edge from a lower layer file to a higher layer file.
Baseline: tests/guard_baseline/guard_deps.json {"READER -> PROVIDER": number of names}. A new pair or a higher count fails.
Outputs: reports/solid-deps-map.md and reports/solid-deps-map.json (rewritten on every run, except with --root, then written next to the scratch copy's tests/out).
Run: python3 tests/guard_deps.py [--root DIR] [--enforce | --strict] [--update-baseline]
--update-baseline is for deliberate use only (after review), never to hide a new back-edge."""
import re, sys, json
from guard_lib import *
o = parse_args('guard_deps')
files = manifest_files(o['root']); order = {f: i for i, f in enumerate(files)}
code = {f: stripped(o['root'], f) for f in files}
KW = set('function return var let const class new this typeof void delete in of if else for while do switch case break continue default try catch finally throw null true false undefined import export from async await yield with'.split())
prov = {}  # name -> set(files)
def add(n, f):
    if len(n) >= 4 and n not in KW: prov.setdefault(n, set()).add(f)
for f in files:
    c = code[f]; bm = brace_map(c)
    # depth 0 declarations: walk the text, skipping the content of top level braces
    depth = 0; i = 0; spans = sorted(bm.items()); top = []; last = 0
    for a, b in spans:
        if a < last: continue
        top.append(c[last:a]); last = b + 1
    top.append(c[last:]); t0 = '{}'.join(top)
    for m in re.finditer(r'\b(?:function\s*\*?|const|let|var|class)\s+([A-Za-z_$][\w$]*)', t0): add(m.group(1), f)
    for m in re.finditer(r'\bexport\s*\{([^}]*)\}', c):
        for nm in m.group(1).split(','):
            nm = nm.split(' as ')[-1].strip()
            if nm: add(nm, f)
    for m in re.finditer(r'\bwindow\s*\.\s*([A-Za-z_$][\w$]*)\s*=(?!=)', c): add(m.group(1), f)
    raw = read(o['root'], f)
    for m in re.finditer(r'defineProperty\(\s*__R\s*,\s*"(\w+)"', raw): add(m.group(1), f)
    for m in re.finditer(r'\b__R\s*\.\s*(\w+)\s*=(?!=)', c): add(m.group(1), f)
uniq = {n: next(iter(fs)) for n, fs in prov.items() if len(fs) == 1}
edges = {}  # (reader, provider) -> {'import':bool, 'names': set}
def edge(r, p, n=None, imp=False):
    if r == p: return
    e = edges.setdefault((r, p), {'import': False, 'names': set()})
    if imp: e['import'] = True
    if n: e['names'].add(n)
for f in files:
    raw = read(o['root'], f); d = os.path.dirname(f)
    for m in re.finditer(r'^\s*import\s+(?:[^"\';]*?\s+from\s+)?"(\.[^"]+)"', raw, re.M):
        p = os.path.normpath(os.path.join(d, m.group(1))).replace(os.sep, '/')
        if p in order: edge(f, p, imp=True)
    idents = set(re.findall(r'[A-Za-z_$][\w$]*', code[f]))
    for n in idents:
        p = uniq.get(n)
        if p and p != f: edge(f, p, n)
LN = {0: 'data', 1: 'logic', 2: 'ui', None: '-'}
back = {}
for (r, p), e in edges.items():
    lr, lp = layer(r), layer(p)
    if lr is not None and lp is not None and lp > lr:
        back['%s -> %s' % (r, p)] = max(len(e['names']), 1 if e['import'] else 0)
base = load_baseline('guard_deps')
if o['update']:
    save_baseline('guard_deps', back); print('baseline written: %d back-edges' % len(back)); sys.exit(0)
bl = base or {}
new = [k for k, v in back.items() if v > bl.get(k, 0)]
# reports
ev = {'files': {f: {'layer': LN[layer(f)], 'order': order[f]} for f in files},
      'edges': [{'from': r, 'to': p, 'import': e['import'], 'names': sorted(e['names'])[:40], 'count': len(e['names'])} for (r, p), e in sorted(edges.items())],
      'back_edges': back}
outdir = os.path.join(o['root'], 'reports') if o['root'] == REPO else os.path.join(HERE, 'out')
os.makedirs(outdir, exist_ok=True)
json.dump(ev, open(os.path.join(outdir, 'solid-deps-map.json'), 'w'), indent=1)
by = {}
for (r, p), e in edges.items():
    key = (LN[layer(r)], LN[layer(p)]); by[key] = by.get(key, 0) + 1
md = ['# SOLID dependency map (generated by tests/guard_deps.py, do not edit by hand)', '',
      'Files in manifest order: %d. Edges: %d. Back-edges (lower layer reads higher layer): %d, new against the baseline: %d.' % (len(files), len(edges), len(back), len(new)), '',
      'Direction rule: data -> builder logic -> UI. data may not read logic or UI, logic may not read UI.', '',
      '## Edges between layers (number of file pairs)', '', '| reader \\ provider | data | logic | ui | unclassified |', '|---|---|---|---|---|']
for a in ('data', 'logic', 'ui', '-'):
    md.append('| %s | %s |' % (a, ' | '.join(str(by.get((a, b), 0)) for b in ('data', 'logic', 'ui', '-'))))
md += ['', '## Back-edges (baseline in tests/guard_baseline/guard_deps.json)', '', '| reader | provider | names | in baseline |', '|---|---|---|---|']
for k, v in sorted(back.items(), key=lambda kv: -kv[1]):
    r, p = k.split(' -> '); nm = ', '.join(sorted(edges[(r, p)]['names'])[:5]) or '(import)'
    md.append('| %s (%s) | %s (%s) | %d: %s | %s |' % (r, LN[layer(r)], p, LN[layer(p)], v, nm, 'yes' if k in bl and v <= bl[k] else 'NEW'))
md += ['', '## Fan-in (most depended on files)', '', '| file | layer | readers |', '|---|---|---|']
fi = {}
for (r, p) in edges: fi[p] = fi.get(p, 0) + 1
for p, n in sorted(fi.items(), key=lambda kv: -kv[1])[:15]: md.append('| %s | %s | %d |' % (p, LN[layer(p)], n))
open(os.path.join(outdir, 'solid-deps-map.md'), 'w').write('\n'.join(md) + '\n')
print('guard_deps: %d files, %d edges, %d back-edges (data->logic/ui or logic->ui)' % (len(files), len(edges), len(back)))
for k, v in sorted(back.items(), key=lambda kv: -kv[1])[:12 if not o['verbose'] else None]: print('  %-80s %d %s' % (k, v, 'NEW/UP' if k in new else ''))
for k in new: print('NEW back-edge:', k, back[k], '(was %s)' % bl.get(k, 0))
sys.exit(finish(o, 'guard_deps', len(back), len(new), {'files': len(files), 'edges': len(edges)}))
