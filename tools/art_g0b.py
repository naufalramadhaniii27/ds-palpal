#!/usr/bin/env python3
"""Step 5 card art. python3 tools/art_g0b.py BATCH_G0_DIR G0_DIR [--dry]
BATCH_G0_DIR = art/batch/g0 of art-batch (corners, divider, badge, crest: the redrawn set). G0_DIR = art/g0 of art-g0 (textures, wipe mask: only there).
Writes img/g0/*.avif and adds the keys to img/manifest.json (g0) and src/fx/23-class-art-data.js."""
import json, os, sys
from PIL import Image, ImageOps
import numpy as np
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BD, GD = sys.argv[1], sys.argv[2]; DRY = "--dry" in sys.argv
OUT = os.path.join(ROOT, "img", "g0"); os.makedirs(OUT, exist_ok=True)
MAN = os.path.join(ROOT, "img", "manifest.json"); man = json.load(open(MAN)); tot = 0; g0 = man.setdefault("g0", {})
def save(im, name, q=60):
    global tot
    p = os.path.join(OUT, name + ".avif"); im.save(p, "AVIF", quality=q, speed=6); tot += os.path.getsize(p); g0[name] = "img/g0/" + name + ".avif"; print(name, im.size, os.path.getsize(p))
def crop(im):  # trim the empty margin so the ornament sits at the card corner
    bb = im.getchannel("A").getbbox(); return im.crop(bb) if bb else im
# corners: drawn for the top-left. tl as drawn, tr mirrored, bl flipped, br both
for c in ("wood", "metal", "vine"):
    im = Image.open(os.path.join(BD, "corner-%s.png" % c)).convert("RGBA"); im = crop(im); im.thumbnail((160, 160), Image.LANCZOS)
    for k, f in (("tl", im), ("tr", ImageOps.mirror(im)), ("bl", ImageOps.flip(im)), ("br", ImageOps.flip(ImageOps.mirror(im)))): save(f, "corner-%s-%s" % (c, k), 62)
im = crop(Image.open(os.path.join(BD, "divider-wood.png")).convert("RGBA")); im = im.resize((1024, round(im.height * 1024 / im.width)), Image.LANCZOS); save(im, "divider-wood", 62)
im = crop(Image.open(os.path.join(BD, "badge-level.png")).convert("RGBA")); im.thumbnail((256, 256), Image.LANCZOS); save(im, "badge-level", 62)
im = crop(Image.open(os.path.join(BD, "crest-app.png")).convert("RGBA")); im.thumbnail((512, 512), Image.LANCZOS); save(im, "crest-app", 62)
# paper: a seamless tile turned into a faint overlay. light = white fibers for dark panels, dark = black fibers for light panels. Alpha stays under 0.14
for t in ("cool", "neutral"):
    im = Image.open(os.path.join(GD, "texture-paper-%s.png" % t)).convert("RGB").resize((512, 512), Image.LANCZOS); a = np.asarray(im).astype(float); lum = a.mean(axis=2); d = lum - lum.mean(); d = d / (np.abs(d).max() or 1)
    tint = a.mean(axis=(0, 1)); tint = tint / tint.max()
    for mode, sgn, col in (("light", 1, np.array([255, 255, 255]) * 0.5 + 255 * tint * 0.5), ("dark", -1, np.array([0, 0, 0]) + 0 * tint)):
        al = np.clip(sgn * d, 0, 1) * 0.14 * 255; rgba = np.zeros((512, 512, 4), dtype=np.uint8); rgba[..., :3] = col.astype(np.uint8); rgba[..., 3] = al.astype(np.uint8)
        save(Image.fromarray(rgba, "RGBA"), "paper-%s-%s" % (t, mode), 50)
# wipe: one black brush stroke on white. Alpha = how black it is, so the stroke is the visible part of a mask
m = Image.open(os.path.join(GD, "wipe-mask-vertical.png")).convert("L").resize((576, 1024), Image.LANCZOS); al = 255 - np.asarray(m)
rgba = np.zeros((1024, 576, 4), dtype=np.uint8); rgba[..., 3] = al; save(Image.fromarray(rgba, "RGBA"), "wipe-mask", 55)
if not DRY:
    json.dump(man, open(MAN, "w"), separators=(",", ":"), sort_keys=True)
    open(os.path.join(ROOT, "src", "fx", "23-class-art-data.js"), "w").write("/* generated by tools/art_pipeline.py. Do not edit by hand */\nwindow.__ART=" + json.dumps(man, sort_keys=True, separators=(",", ":")) + ";\n")
print("KB added: %.0f" % (tot / 1024))
