"""Writes src/data/fx-B21-staticsense.js: senses that a subclass feature or a feat states plainly and always (Darkvision to N feet, Blindsight, Truesight or Tremorsense out to N feet).
Usage: python3 tools/gen_staticsense.py <gate data cache .json>   (use a cache made before the output file exists)
Skips a feature when its level is not unique in the data files, when another fx file already names it, when the sentence is timed, a familiar's, or has other numbers or conditions."""
import sys, json, re, datetime, os, glob
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, os.path.join(ROOT, "tests"))
import clause_gate as g
D = json.load(open(sys.argv[1])); g.build_index(D)
bd = g.load_by_design(); al = g.load_allow()
feats, res, ctx = g.scan(D, bd, al, datetime.date.today().isoformat())
ALLF = {f: open(f, encoding="utf8").read() for f in glob.glob(os.path.join(ROOT, "src", "data", "*.js")) if "fx-B21" not in f}
FXF = {f: t for f, t in ALLF.items() if os.path.basename(f).startswith("fx-")}
def levels(sub, feat):
    base = re.sub(r" \((?:2014|PSA|Deep Magic|Banneret)\)$", "", sub); lv = set()
    for f, t in ALLF.items():
        for m in re.finditer(r'"name":"' + re.escape(base) + '"', t):
            seg = t[m.end():m.end() + 40000]; n = seg.find('"name":"'); seg = seg[:n] if n > 0 else seg
            for h in re.finditer(r'\[(\d+),"' + re.escape(feat) + '"', seg): lv.add(int(h.group(1)))
    return lv
def named(owner, feat):
    q, f = json.dumps(owner), json.dumps(feat)
    return any(q in line and (("n:" + f) in line or ('"n":' + f) in line or ("," + f + ",") in line) for t in FXF.values() for line in t.split("\n"))
SENSES = "Darkvision|Blindsight|Truesight|Tremorsense"
RX = re.compile(r"^(?:You |Your [a-z ]+ )?(?:gain|have|also gain) (" + SENSES + r") (?:with a range of |out to |to |of )?(\d+) (?:feet|ft)\.?(?: \(?If you already have (?:it|darkvision), (?:the range|its range) (?:increases|grows|rises) by (\d+) (?:feet|ft)\)?\.?)?$", re.I)
SKIP = {"Moonsight"}  # Moonsight already gets its Darkvision from the Witch spec rewrite in fx-L13 (a second row would add 60 ft twice)
rows = {"sub": {}, "feat": {}}
for r in res:
    if r["status"] != "uncovered" or r["kind"] not in ("sub", "feat") or "SENSE" not in r["why"]: continue
    t = re.sub(r"^[-\s]+", "", r["text"].strip())
    if re.search(r"familiar|Charm|minute|hour|expend|underwater|magical darkness|Bonus Action|As an action|Dim Light", t, re.I): continue
    m = RX.match(t)
    if not m: continue
    typ, n = m.group(1).title(), int(m.group(2)); extra = int(m.group(3)) if m.group(3) else 0
    e = {}
    if typ == "Darkvision":
        if extra:
            if extra != n: continue
            e["darkAdd"] = n
        else: e["darkTo"] = n
    else:
        if extra: continue
        e["sense"] = [[typ, n, ""]]
    if r["kind"] == "sub":
        owner = r["owner"].split("/", 1)[1]; lv = levels(owner, r["name"])
        if len(lv) != 1: continue
        e["l"] = min(lv)
    else:
        owner = r["name"]
    if named(owner, r["name"]) or r["name"] in SKIP: continue
    e = dict({"n": r["name"] + " (sense)"}, **e)
    rows[r["kind"]].setdefault(owner, {})[r["name"]] = e
out = ["DataEnv.slot.GX=DataEnv.slot.GX||{};GX.sub=GX.sub||{};GX.feat=GX.feat||{};", "/* fx data batch B21 (generated by tools/gen_staticsense.py): senses that a subclass feature or a feat states plainly and always. Do not edit by hand. */", "(function(){", "var S=function(k,e){GX.sub[k]=(GX.sub[k]||[]).concat(e)};", "var F=function(k,e){GX.feat[k]=(GX.feat[k]||[]).concat([e])};"]
n = 0
for k in sorted(rows["sub"]):
    out.append("S(%s,%s);" % (json.dumps(k), json.dumps(list(rows["sub"][k].values()), ensure_ascii=False))); n += len(rows["sub"][k])
for k in sorted(rows["feat"]):
    for e in rows["feat"][k].values(): out.append("F(%s,%s);" % (json.dumps(k), json.dumps(e, ensure_ascii=False))); n += 1
out.append("})();")
open(os.path.join(ROOT, "src", "data", "fx-B21-staticsense.js"), "w", encoding="utf8").write("\n".join(out) + "\n")
print("wrote", n, "rows")
