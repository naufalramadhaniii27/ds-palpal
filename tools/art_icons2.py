#!/usr/bin/env python3
"""Installs Codex icons that have a place in the app and no 5etools picture. python3 tools/art_icons2.py CODEX_ICONS_DIR HAS5.json [--dry]
CODEX_ICONS_DIR is art/batch/icons of the Codex branch. HAS5.json comes from tools/art_elig.py. Writes img/icon/<cat>/<slug>.avif (128 px)
and updates img/manifest.json and src/fx/23-class-art-data.js. Categories: items, spells, feats, features, bastion (facility)."""
import json, os, sys
from PIL import Image
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC, H5 = sys.argv[1], json.load(open(sys.argv[2])); DRY = "--dry" in sys.argv
MAPK = {"items": ("item", "item"), "spells": ("spell", "spell"), "feats": ("feat", "feat"), "features": ("feature", "feature"), "bastion": ("facility", "facility")}
PRE = ["eldritch-invocation-", "battle-master-maneuver-", "metamagic-", "language-"]
def rules_target(sl):
    """rules/* icons are named after the picture, not the entry: strip the type word and look the entry up as rule, option, optional feature or language"""
    c = [sl] + [sl[len(p):] for p in PRE if sl.startswith(p)] + ([sl[:-7]] if sl.endswith("-action") else [])
    for x in c:
        for k in ("rule", "opt", "optfeat", "language"):
            if x in H5.get(k, {}): return k, x
    return None, None
MAN = os.path.join(ROOT, "img", "manifest.json"); man = json.load(open(MAN)); man.setdefault("icon", {})
tot = n = 0
for top, (cat, kind) in MAPK.items():
    app = H5[kind]; seen = set(man["icon"].get(cat, []))
    for dp, _, fs in sorted(os.walk(os.path.join(SRC, top))):
        for f in sorted(fs):
            if not f.endswith(".png"): continue
            s = f[:-4]
            if s not in app or app[s] or s in seen: continue
            seen.add(s); n += 1
            if DRY: continue
            os.makedirs(os.path.join(ROOT, "img", "icon", cat), exist_ok=True); dst = os.path.join(ROOT, "img", "icon", cat, s + ".avif")
            im = Image.open(os.path.join(dp, f)).convert("RGBA"); im.thumbnail((128, 128), Image.LANCZOS); im.save(dst, "AVIF", quality=60, speed=6); tot += os.path.getsize(dst)
    man["icon"][cat] = sorted(seen)
# rules/*: the entry kind decides the folder
rn = 0
for dp, _, fs in sorted(os.walk(os.path.join(SRC, "rules"))):
    for f in sorted(fs):
        if not f.endswith(".png"): continue
        k, x = rules_target(f[:-4])
        if not k or H5[k][x]: continue
        seen = set(man["icon"].get(k, []))
        if x in seen: continue
        n += 1
        if not DRY:
            os.makedirs(os.path.join(ROOT, "img", "icon", k), exist_ok=True); dst = os.path.join(ROOT, "img", "icon", k, x + ".avif")
            im = Image.open(os.path.join(dp, f)).convert("RGBA"); im.thumbnail((128, 128), Image.LANCZOS); im.save(dst, "AVIF", quality=60, speed=6); tot += os.path.getsize(dst)
            man["icon"][k] = sorted(seen | {x})
print(n, "new icons", tot // 1024, "KB")
if not DRY:
    json.dump(man, open(MAN, "w"), indent=1, sort_keys=True)
    open(os.path.join(ROOT, "src", "fx", "23-class-art-data.js"), "w").write("/* generated by tools/art_pipeline.py. Do not edit by hand */\nwindow.__ART=" + json.dumps(man, sort_keys=True, separators=(",", ":")) + ";\n")
