"""Writes src/data/fx-B31-subres.js: damage resistances stated in the text of a subclass feature, as res records (static, or on a switch).
Usage: python3 tools/gen_subres.py <gate data cache .json>   (use a cache made before the output file exists)
Only the features in CURATED are written (each was read by hand). A feature needs one unique level; a feature another file already names is skipped."""
import sys, json, re, datetime, os, glob
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, os.path.join(ROOT, "tests"))
import clause_gate as g
D = json.load(open(sys.argv[1])); g.build_index(D)
bd = g.load_by_design(); al = g.load_allow()
feats, res, ctx = g.scan(D, bd, al, datetime.date.today().isoformat())
ALLF = {f: open(f, encoding="utf8").read() for f in glob.glob(os.path.join(ROOT, "src", "data", "*.js")) if "fx-B31" not in f}
BPS = ["Bludgeoning", "Piercing", "Slashing"]
ALL = ["Acid", "Bludgeoning", "Cold", "Fire", "Force", "Lightning", "Necrotic", "Piercing", "Poison", "Psychic", "Radiant", "Slashing", "Thunder"]
# feature -> (resistances, switch). switch None = always, "rage" = follows the Rage mode, else the label of a new switch
CURATED = {
 "Frigid Explorer": (["Cold"], None), "Elemental Champion": (["Acid", "Cold", "Fire", "Lightning", "Thunder"], None),
 "Superior Dread": (BPS, None), "Endless Evolution": (BPS, None), "Aura of Warmth": (["Cold", "Fire"], None), "Sun's Warmth": (["Cold", "Fire"], None),
 "Aura of Deathly Endurance": (["Cold", "Necrotic", "Psychic"], None), "Secrets of Deep Imaskar": (["Radiant"], None),
 "Otherworldly Anguish": (["Cold", "Necrotic"], "rage"), "Brains and Brawn": (None, "rage"),
 "Thick Hide": (BPS, "Thick Hide"), "Protect Life": (["Necrotic"], "Protect Life"), "Adamantine Hide": (BPS, "Wild Shape"), "Full of Stars": (BPS, "Starry Form"),
}
def levels(sub, feat):
    base = re.sub(r" \((?:2014|PSA|Deep Magic|Banneret)\)$", "", sub); lv = set()
    for f, t in ALLF.items():
        for m in re.finditer(r'"name":"' + re.escape(base) + '"', t):
            seg = t[m.end():m.end() + 40000]; n = seg.find('"name":"'); seg = seg[:n] if n > 0 else seg
            for h in re.finditer(r'\[(\d+),"' + re.escape(feat) + '"', seg): lv.add(int(h.group(1)))
    return lv
def named(owner, feat):
    q, f = json.dumps(owner), json.dumps(feat)
    return any(q in line and (("n:" + f) in line or ('"n":' + f) in line) and re.search(r"\b(?:res|imm)\b\"?:", line) for t in ALLF.values() for line in t.split("\n") if os.path.basename("") == "")
rows = {}
for r in res:
    if r["status"] != "uncovered" or r["kind"] != "sub" or "RES" not in r["why"] or r["name"] not in CURATED: continue
    owner = r["owner"].split("/", 1)[1]
    if (owner, r["name"]) in rows: continue
    lv = levels(owner, r["name"])
    if len(lv) != 1: print("skip level", owner, r["name"], lv); continue
    ty, sw = CURATED[r["name"]]
    if ty is None: ty = [x for x in ALL if x != "Psychic" and (x != "Force" or "(2014)" not in owner)]; ty = [x for x in ALL if x not in (("Psychic",) if "(2014)" in owner else ("Force", "Psychic"))]
    e = {"n": r["name"], "l": min(lv), "res": ty}
    if sw == "rage": e["toggle"] = {"id": "rage", "label": "Raging"}
    elif sw: e["toggle"] = {"id": "b31-" + re.sub(r"[^a-z0-9]+", "-", r["name"].lower()).strip("-"), "label": sw}
    rows[(owner, r["name"])] = e
out = ["DataEnv.slot.GX=DataEnv.slot.GX||{};GX.sub=GX.sub||{};", "/* fx data batch B31 (generated by tools/gen_subres.py): damage resistances of subclass features, static or on a switch. Do not edit by hand. */", "(function(){", "var S=function(k,e){GX.sub[k]=(GX.sub[k]||[]).concat(e)};"]
by = {}
for (o, n), e in rows.items(): by.setdefault(o, []).append(e)
for o in sorted(by): out.append("S(%s,%s);" % (json.dumps(o, ensure_ascii=False), json.dumps(by[o], ensure_ascii=False)))
out.append("})();")
open(os.path.join(ROOT, "src", "data", "fx-B31-subres.js"), "w", encoding="utf8").write("\n".join(out) + "\n")
print(len(rows), "features")
