"""Writes src/data/fx-B13-itemres.js: Resistance rows for items whose sentence plainly gives Resistance to one fixed damage type while carried or worn.
Usage: python3 tools/gen_itemres.py <gate data cache .json>   (use a cache made before the output file exists)
Skips conditional wording (action, first time, chosen, until, one of, breath, nonmagical, from those) and items another fx file already names."""
import sys, json, re, datetime, os, glob
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, os.path.join(ROOT, "tests"))
import clause_gate as g
D = json.load(open(sys.argv[1])); g.build_index(D)
bd = g.load_by_design(); al = g.load_allow()
feats, res, ctx = g.scan(D, bd, al, datetime.date.today().isoformat())
FILES = {f: open(f, encoding="utf8").read() for f in glob.glob(os.path.join(ROOT, "src", "data", "fx-*.js")) if "fx-B13" not in f}
TYPES = "Acid|Bludgeoning|Cold|Fire|Force|Lightning|Necrotic|Piercing|Poison|Psychic|Radiant|Slashing|Thunder"
BAD = re.compile(r"as an action|first time|chosen|choice|until|one of|breath|nonmagical|from those|that the donor|your next|when you|while raging|if you", re.I)
SKIP = {"Flammable Tincture", "Staff of Light and Shadow", "Ironleaf Plate",  # a curse on a target, two alternating states, a benefit that ends when Fire damage hits
        "Kwark's Wondrous Kernels, Planter", "Psionic Piercing", "Gazing Hydrangea"}  # only from one d8 result, a property re-picked each dawn, a crown made in a ritual
OWN = {}  # the item row's own fx.res: 12j-logic-sheet-handlers-features.js already lists it, a B13 row would list it twice
for r in list(D["dmgi"]) + [x for v in D["wxi"].values() for x in v]:
    OWN.setdefault(r[0], set()).update((((r[5] if len(r) > 5 else None) or {}).get("fx") or {}).get("res") or [])
def named(name): q = json.dumps(name); return any(q in t for t in FILES.values())
rows = {}
for r in res:
    if r["status"] != "uncovered" or r["kind"] != "item" or "(" in r["name"]: continue
    t = re.sub(r"^[-\s]+", "", r["text"].strip())
    m = re.search(r"\bresistance to (" + TYPES + r") damage\b", t, re.I)
    if not m or BAD.search(t) or len(t) > 200 or named(r["name"]) or r["name"] in SKIP: continue
    if len(re.findall(r"resistance to", t, re.I)) != 1: continue
    if m.group(1).capitalize() in OWN.get(r["name"], ()): continue
    rows.setdefault(r["name"], set()).add(m.group(1).capitalize())
out = ["DataEnv.slot.GX=DataEnv.slot.GX||{};", "/* fx data batch B13 (generated by tools/gen_itemres.py): Resistance that magic items give plainly while carried or worn. Do not edit by hand. */", "(function(){", "var G=DataEnv.slot.GX.item=DataEnv.slot.GX.item||{};", "var add=function(n,t){(G[n]=G[n]||[]).push({n:n+\" (resistance)\",defs:t.map(function(x){return [\"Resistance\",x]})})};"]
for k in sorted(rows): out.append("add(%s,%s);" % (json.dumps(k, ensure_ascii=False), json.dumps(sorted(rows[k]))))
out.append("})();")
open(os.path.join(ROOT, "src", "data", "fx-B13-itemres.js"), "w", encoding="utf8").write("\n".join(out) + "\n")
print(len(rows), "items:", ", ".join(sorted(rows)))
