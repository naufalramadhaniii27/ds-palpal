#!/usr/bin/env python3
"""N46: writes src/globals.d.ts, one `declare var NAME: any;` for every data global the code reads without importing (SPECIES, CLASSES, SPELLS and the like).
Input: the text of a tsc run with checkJs on (python3 tools/ts_globals.py tsc-all.txt). The names are the ones TS2304 reports. The list is kept sorted so the file changes only when a name is added.
Names that are real locals of a file would have been found by tsc itself, so this list only holds names that no file declares."""
import re, sys
names = set(re.findall(r"error TS2304: Cannot find name '([^']+)'", open(sys.argv[1], encoding="utf-8").read()))
try: old = set(re.findall(r"declare var (\w+): any;", open("src/globals.d.ts", encoding="utf-8").read()))
except FileNotFoundError: old = set()
names |= old
body = "/* Generated by tools/ts_globals.py (N46). Data globals that are filled by the deferred data parts at run time. Typed any until a data type is written for them. */\n" + "".join("declare var %s: any;\n" % n for n in sorted(names))
open("src/globals.d.ts", "w", encoding="utf-8").write(body); print(len(names), "names")
