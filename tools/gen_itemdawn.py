"""Writes src/data/fx-B30-itemdawn.js: item spells that can be cast once each until the next dawn. Sets the 5th field of the ITEM_SPELLS pair to "dawn"; the sheet then adds one once-per-Long-Rest counter per spell and the cast button respects it.
Usage: python3 tools/gen_itemdawn.py <gate data cache .json>   (use a cache made before the output file exists)"""
import sys, json, re, datetime, os
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, os.path.join(ROOT, "tests"))
import clause_gate as g
D = json.load(open(sys.argv[1])); g.build_index(D)
bd = g.load_by_design(); al = g.load_allow()
feats, res, ctx = g.scan(D, bd, al, datetime.date.today().isoformat())
RX = re.compile(r"can't (?:be used to )?cast (?:that |the |this |it |that same )?(?:spell )?(?:it )?again until (?:the next )?dawn|can't (?:cast|be used) .{0,40}until (?:the next )?dawn", re.I)
IS = D["itemSpells"]; names = {}
for r in res:
    if r["status"] != "uncovered" or r["kind"] != "item" or "SPELL" not in r["why"] or not RX.search(r["text"]): continue
    e = IS.get(r["name"])
    if not e or not e.get("sp"): continue
    sp = [q[0] for q in e["sp"] if q[1]]
    if sp: names[r["name"]] = sp
out = ["/* Generated by tools/gen_itemdawn.py. Do not edit by hand. Item spells that can be cast once each until the next dawn. */", "(function(){", "if(typeof ITEM_SPELLS==='undefined')return;",
       "var L=" + json.dumps(names, sort_keys=True, ensure_ascii=False) + ";",
       "Object.keys(L).forEach(function(n){var o=ITEM_SPELLS[n];if(!o)return;o.sp.forEach(function(q){if(L[n].indexOf(q[0])>=0){while(q.length<4)q.push(0);q[4]='dawn'}})});", "})();"]
open(os.path.join(ROOT, "src", "data", "fx-B30-itemdawn.js"), "w", encoding="utf8").write("\n".join(out) + "\n")
print(len(names), "items", sum(len(v) for v in names.values()), "spells")
