#!/usr/bin/env python3
"""Installs the Codex art made for the Learn screens. python3 tools/art_learn.py CODEX_BATCH_DIR
CODEX_BATCH_DIR is art/batch of the Codex branch. Writes
  scenes/screen/learn*       to img/scn/screen/<id>-pc|phone.avif   (2400 / 1088 px wide, like tools/art_pipeline.py)
  vignettes/learn/<id>.png   to img/vig/learn/<id>.avif             512 px, alpha kept
  emblems/learn/<id>.png     to img/emblem/learn/<id>.avif          384 px, alpha kept
  icons/learn/<id>.png       to img/icon/learn/<id>.avif            128 px, alpha kept
and records them in img/manifest.json and src/fx/23-class-art-data.js. Safe to run again."""
import json, os, sys
from PIL import Image
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = sys.argv[1]; OUT = os.path.join(ROOT, "img"); MAN = os.path.join(OUT, "manifest.json")
man = json.load(open(MAN)); tot = 0; log = {}
def avg(im): return "#%02x%02x%02x" % im.convert("RGB").resize((1, 1), Image.LANCZOS).getpixel((0, 0))
def put(im, dst, q):
    os.makedirs(os.path.dirname(dst), exist_ok=True); im.save(dst, "AVIF", quality=q, speed=6); return os.path.getsize(dst)
def pngs(*p):
    d = os.path.join(SRC, *p)
    return [(f[:-4], os.path.join(d, f)) for f in sorted(os.listdir(d)) if f.endswith(".png")] if os.path.isdir(d) else []
scr = man.setdefault("scn", {}).setdefault("screen", {}); n = 0
for k, f in pngs("scenes", "screen"):
    kind = "pc" if k.endswith("-pc") else "phone" if k.endswith("-phone") else None
    cid = k.rsplit("-", 1)[0]
    if not kind or not cid.startswith("learn"): continue
    im = Image.open(f).convert("RGB"); w = 2400 if kind == "pc" else 1088
    if im.width > w: im = im.resize((w, round(im.height * w / im.width)), Image.LANCZOS)
    tot += put(im, os.path.join(OUT, "scn", "screen", k + ".avif"), 54)
    e = scr.setdefault(cid, {}); e[kind] = "img/scn/screen/%s.avif" % k; e["c"] = avg(im); n += 1
log["screens"] = n
for key, top, sub, px, q in (("vig", "vignettes", "learn", 512, 58), ("elearn", "emblems", "learn", 384, 62), ("icon", "icons", "learn", 128, 60)):
    ids = []
    for k, f in pngs(top, sub):
        im = Image.open(f).convert("RGBA"); im.thumbnail((px, px), Image.LANCZOS)
        dst = {"vig": "vig/learn", "elearn": "emblem/learn", "icon": "icon/learn"}[key]
        tot += put(im, os.path.join(OUT, dst, k + ".avif"), q); ids.append(k)
    if key == "vig": man["vig"]["learn"] = ids
    elif key == "icon": man["icon"]["learn"] = ids
    else: man[key] = ids
    log[sub + "/" + top] = len(ids)
json.dump(man, open(MAN, "w"), indent=1, sort_keys=True)
open(os.path.join(ROOT, "src", "fx", "23-class-art-data.js"), "w").write("/* generated by tools/art_pipeline.py. Do not edit by hand */\nvar __ART=" + json.dumps(man, sort_keys=True, separators=(",", ":")) + ";\n")
print(log, tot // 1024, "KB")
