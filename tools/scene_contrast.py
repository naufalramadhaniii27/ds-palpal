#!/usr/bin/env python3
"""Contrast audit for scene art. python3 tools/scene_contrast.py [--write]
--write stores the strongest opacity that still passes (key "o": {pc, ph}) in img/manifest.json and src/fx/23-class-art-data.js. Run it after every art_pipeline.py run.
Composites every scene at its shown opacity over the page colour and measures the text colour against the worst 5 percent of pixels
(brightest for dark pages, darkest for light pages). WCAG ratio, pass at 4.5. With stored limits ("o") the sheet scenes are measured at that opacity. Text that sits on cards is not in scope, cards are solid."""
import json, os, sys
import warnings; warnings.simplefilter('ignore')
from PIL import Image
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
M = json.load(open(os.path.join(ROOT, "img", "manifest.json")))
def lin(c): c /= 255.0; return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4
def lum(rgb): return 0.2126 * lin(rgb[0]) + 0.7152 * lin(rgb[1]) + 0.0722 * lin(rgb[2])
def hexrgb(h): h = h.lstrip("#"); return tuple(int(h[i:i+2], 16) for i in (0, 2, 4))
def ratio(a, b): a, b = max(a, b), min(a, b); return (a + 0.05) / (b + 0.05)
SKINS = {"dark": ((12, 20, 17), hexrgb("#e3eae4"), True), "light": (hexrgb("#e5e8df"), hexrgb("#141d18"), False)}
def scenes():
    for c, s in M["scene"].items():
        yield "class/" + c, s["pc"]["p"], s["phone"]["p"], True, s.get("o")
    for g, d in M["scn"].items():
        for i, s in d.items():
            if "pc" not in s or "phone" not in s: print("no pc/phone pair:", g, i); continue
            yield "scn/%s/%s" % (g, i), s["pc"], s["phone"], g in ("tab", "screen"), s.get("o")
def worst(path, op, bg, ink, dark):
    im = Image.open(os.path.join(ROOT, path)).convert("RGB"); im.thumbnail((240, 240))
    L = sorted(lum(tuple(int(v * op + b * (1 - op)) for v, b in zip(p, bg))) for p in im.getdata())
    k = L[int(len(L) * 0.95)] if dark else L[int(len(L) * 0.05)]
    return ratio(lum(ink), k)
def best(path, top):
    path = os.path.join(ROOT, path)
    """Largest opacity up to top where both skins stay at 4.5 or more"""
    o = top
    while o > 0.08:
        o = int(o * 100 + 1e-9) / 100.0
        if all(worst(path, o, bg, ink, dark) >= 4.5 for bg, ink, dark in SKINS.values()): return o
        o -= 0.01
    return 0.08
if "--write" in sys.argv:
    n = 0
    def put(e, sheet):
        global n
        pc = e["pc"]["p"] if isinstance(e["pc"], dict) else e["pc"]; ph = e["phone"]["p"] if isinstance(e["phone"], dict) else e["phone"]
        e["o"] = {"pc": best(pc, .55), "ph": best(ph, .40)}; n += 1
    for c, e in M["scene"].items(): put(e, True)
    for g in ("tab", "screen"):
        for i, e in M["scn"].get(g, {}).items():
            if "pc" in e and "phone" in e: put(e, True)
    json.dump(M, open(os.path.join(ROOT, "img", "manifest.json"), "w"), sort_keys=True, separators=(",", ":"))
    open(os.path.join(ROOT, "src", "fx", "23-class-art-data.js"), "w").write("/* generated by tools/art_pipeline.py. Do not edit by hand */\nwindow.__ART=" + json.dumps(M, sort_keys=True, separators=(",", ":")) + ";\n")
    print("wrote opacity for %d scenes" % n); sys.exit(0)
bad = 0; rows = []
for name, pc, ph, sheet, o in scenes():
    for kind, path, op in (("pc", pc, (o or {}).get("pc", .55) if sheet else .22), ("phone", ph, (o or {}).get("ph", .4) if sheet else .16)):
        for sk, (bg, ink, dark) in SKINS.items():
            r = worst(path, op, bg, ink, dark); rows.append((r, name, kind, sk))
rows.sort()
for r, n, k, sk in rows[:12]: print("%5.2f  %-34s %-5s %s" % (r, n, k, sk))
fails = [x for x in rows if x[0] < 4.5]
print("scenes x skins checked: %d, below 4.5: %d" % (len(rows), len(fails)))
sys.exit(1 if fails else 0)
