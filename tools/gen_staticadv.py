"""Writes src/data/fx-B22-staticadv.js: Advantage that a subclass feature, a feat or an item states plainly and always, as an advantage note (advOn): "You have Advantage on ...".
Usage: python3 tools/gen_staticadv.py <gate data cache .json>   (use a cache made before the output file exists)
Skips a feature when its level is not unique in the data files, when another fx file already names it, when the sentence is timed, a familiar's, or has other numbers or conditions."""
import sys, json, re, datetime, os, glob
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, os.path.join(ROOT, "tests"))
import clause_gate as g
D = json.load(open(sys.argv[1])); g.build_index(D)
bd = g.load_by_design(); al = g.load_allow()
feats, res, ctx = g.scan(D, bd, al, datetime.date.today().isoformat())
ALLF = {f: open(f, encoding="utf8").read() for f in glob.glob(os.path.join(ROOT, "src", "data", "*.js")) if "fx-B22" not in f}
FXF = {f: t for f, t in ALLF.items() if os.path.basename(f).startswith("fx-")}
def levels(sub, feat):
    base = re.sub(r" \((?:2014|PSA|Deep Magic|Banneret)\)$", "", sub); lv = set()
    for f, t in ALLF.items():
        for m in re.finditer(r'"name":"' + re.escape(base) + '"', t):
            seg = t[m.end():m.end() + 40000]; n = seg.find('"name":"'); seg = seg[:n] if n > 0 else seg
            for h in re.finditer(r'\[(\d+),"' + re.escape(feat) + '"', seg): lv.add(int(h.group(1)))
    return lv
def named(owner, feat):
    q, f = json.dumps(owner), json.dumps(feat)
    return any(q in line and (("n:" + f) in line or ('"n":' + f) in line or ("," + f + ",") in line) for t in FXF.values() for line in t.split("\n"))
RX = re.compile(r"^(?:You|Your [a-z]+) (?:also )?(?:have|gain) advantage on ([^.]+)\.?$", re.I)
BAD = re.compile(r"\b(?:that|those|them|it|then|this|first|up to|covered|detects?|while|when|if|until|after|before|against a creature)\b|\d|\bResistance\b|\bImmunity\b|\bdamage\b", re.I)
TIMED = {"Cape of Enlargement", "Potion of Aqueous Form"}  # active only while enlarged or while the potion lasts: B19 holds the switch
rows = {"sub": {}, "feat": {}, "item": {}}
for r in res:
    if r["status"] != "uncovered" or r["kind"] not in rows or "ADV" not in r["why"]: continue
    t = re.sub(r"^[-\s]+", "", r["text"].strip())
    m = RX.match(t)
    if not m or BAD.search(m.group(1)): continue
    clause = m.group(1).strip()
    clause = clause[0].upper() + clause[1:]
    e = {"advOn": [clause]}
    if r["kind"] == "sub":
        owner = r["owner"].split("/", 1)[1]; lv = levels(owner, r["name"])
        if len(lv) != 1: continue
        e["l"] = min(lv)
    else:
        owner = r["name"]
    if named(owner, r["name"]) or owner in TIMED: continue
    e = dict({"n": r["name"] + " (advantage)"}, **e)
    rows[r["kind"]].setdefault(owner, {})[r["name"]] = e
out = ["DataEnv.slot.GX=DataEnv.slot.GX||{};GX.sub=GX.sub||{};GX.feat=GX.feat||{};GX.item=GX.item||{};", "/* fx data batch B22 (generated by tools/gen_staticadv.py): advantage that a subclass feature, a feat or an item states plainly and always, as an advantage note. Do not edit by hand. */", "(function(){", "var S=function(k,e){GX.sub[k]=(GX.sub[k]||[]).concat(e)};", "var F=function(k,e){GX.feat[k]=(GX.feat[k]||[]).concat([e])};", "var I=function(k,e){GX.item[k]=(GX.item[k]||[]).concat([e])};"]
n = 0
for k in sorted(rows["sub"]):
    out.append("S(%s,%s);" % (json.dumps(k), json.dumps(list(rows["sub"][k].values()), ensure_ascii=False))); n += len(rows["sub"][k])
for kind, fn in (("feat", "F"), ("item", "I")):
    for k in sorted(rows[kind]):
        for e in rows[kind][k].values(): out.append("%s(%s,%s);" % (fn, json.dumps(k), json.dumps(e, ensure_ascii=False))); n += 1
out.append("})();")
open(os.path.join(ROOT, "src", "data", "fx-B22-staticadv.js"), "w", encoding="utf8").write("\n".join(out) + "\n")
print("wrote", n, "rows")
