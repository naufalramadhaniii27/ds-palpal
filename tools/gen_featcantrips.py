"""Writes src/data/fx-B17-featcantrips.js: the cantrip (or spell) a feat teaches by name, with the spellcasting ability the feat text states.
Usage: python3 tools/gen_featcantrips.py <gate data cache .json>
Two readings only: "the ability raised by this feat" (spCls @asi) and "choose Intelligence, Wisdom or Charisma" (spCls @abpick with an ability pick). Feats with other wording or an fx entry that already has spells are skipped."""
import sys, json, re, os, glob
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
D = json.load(open(sys.argv[1]))
FX = "".join(open(f, encoding="utf8").read() for f in glob.glob(os.path.join(ROOT, "src", "data", "fx-*.js")) if "fx-B17" not in f)
SKIP = {"Arcane Overload"}  # the Crucible Storm Chaser background already gives Fire Bolt, so the spell list would show Fire Bolt twice (tests/invariants.py dup-attack)
rows = {}
for n, f in D["feats"].items():
    t = f.get("full") or f.get("d") or ""
    m = re.findall(r"You (?:learn|know) the ([A-Z][A-Za-z' ]+?) (?:cantrip|spell)\b", t)
    if len(m) != 1: continue
    asi = bool(re.search(r"ability (?:raised|increased) by this feat", t))
    ch = bool(re.search(r"(?:[Cc]hoose|pick) Intelligence, Wisdom,? or Charisma as", t))
    if not (asi or ch): continue
    if n in SKIP: continue
    q = re.escape(json.dumps(n))
    if re.search(q + r"[^\n]{0,400}spells\s*:", FX) or re.search(r"\{n:" + q + r"[^\n]{0,300}spells", FX): continue
    e = {"n": n + " (spell)", "spells": [[1, m[0]]]}
    if asi: e["spCls"] = "@asi"
    else:
        e["spCls"] = "@abpick"; e["pick"] = [{"k": "ab", "t": "multi", "n": 1, "title": "Spellcasting ability", "list": [["INT", ""], ["WIS", ""], ["CHA", ""]]}]
    rows[n] = e
out = ["DataEnv.slot.GX=DataEnv.slot.GX||{};GX.feat=GX.feat||{};", "/* fx data batch B17 (generated by tools/gen_featcantrips.py): the cantrip or spell a feat teaches by name. Do not edit by hand. */", "(function(){", "var P=function(k,e){GX.feat[k]=(GX.feat[k]||[]).concat([e])};"]
for k in sorted(rows): out.append("P(%s,%s);" % (json.dumps(k, ensure_ascii=False), json.dumps(rows[k], ensure_ascii=False)))
out.append("})();")
open(os.path.join(ROOT, "src", "data", "fx-B17-featcantrips.js"), "w", encoding="utf8").write("\n".join(out) + "\n")
print(len(rows), "feats:", ", ".join(sorted(rows)))
