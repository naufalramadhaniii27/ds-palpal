"""Writes src/data/fx-B18-subskills2.js: skill proficiencies that a subclass feature states plainly: one named skill (skillProf) or one skill chosen from a short list (a skills pick).
Usage: python3 tools/gen_subskills.py <gate data cache .json>   (use a cache made before the output file exists)
Skips a feature when its level is not unique in the data files, when another fx file already names the subclass feature, or when the sentence has other numbers."""
import sys, json, re, datetime, os, glob
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, os.path.join(ROOT, "tests"))
import clause_gate as g
D = json.load(open(sys.argv[1])); g.build_index(D)
bd = g.load_by_design(); al = g.load_allow()
feats, res, ctx = g.scan(D, bd, al, datetime.date.today().isoformat())
ALLF = {f: open(f, encoding="utf8").read() for f in glob.glob(os.path.join(ROOT, "src", "data", "*.js")) if "fx-B18" not in f}
FXF = {f: t for f, t in ALLF.items() if os.path.basename(f).startswith("fx-")}
SK = "Acrobatics|Animal Handling|Arcana|Athletics|Deception|History|Insight|Intimidation|Investigation|Medicine|Nature|Perception|Performance|Persuasion|Religion|Sleight of Hand|Stealth|Survival"
def levels(sub, feat):
    base = re.sub(r" \((?:2014|PSA|Deep Magic|Banneret)\)$", "", sub); lv = set()
    for f, t in ALLF.items():
        for m in re.finditer(r'"name":"' + re.escape(base) + '"', t):
            seg = t[m.end():m.end() + 40000]; n = seg.find('"name":"'); seg = seg[:n] if n > 0 else seg
            for h in re.finditer(r'\[(\d+),"' + re.escape(feat) + '"', seg): lv.add(int(h.group(1)))
    return lv
def named(sub, feat):
    """True when an fx data line that names this subclass also names the feature (as an entry n or a [level, feature] row)."""
    q, f = json.dumps(sub), json.dumps(feat)
    return any(q in line and (("n:" + f) in line or ('"n":' + f) in line or ("," + f + ",") in line) for t in FXF.values() for line in t.split("\n"))
out_rows = {}
for r in res:
    if r["status"] != "uncovered" or r["kind"] != "sub" or r.get("unexplained") or "PROF" not in r["why"]: continue
    t = re.sub(r"^[-\s]+", "", r["text"].strip()).rstrip(".")
    if len(t) > 150 or re.search(r"\d|tool|weapon|armor|saving|instrument|language|expertise|double|add ", t, re.I): continue
    m = re.match(r"(?:You )?[Gg]ain proficiency in ((?:(?:" + SK + r")(?:, | or | and )?)+)(?: \(your choice\)|, your choice)?$", t)
    if not m: continue
    names = re.findall(SK, m.group(1)); choice = bool(re.search(r"\bor\b|your choice", t)); both = " and " in m.group(1) and not choice
    if not names or (len(names) > 1 and not choice and not both): continue
    sn = r["owner"].split("/", 1)[1]; lv = levels(sn, r["name"])
    if len(lv) != 1 or named(sn, r["name"]): continue
    e = {"n": r["name"] + " (skills)", "l": min(lv)}
    if choice and len(names) > 1: e["pick"] = [{"k": "skill", "t": "skills", "n": 1, "from": names, "title": r["name"] + " skill"}]
    else: e["skillProf"] = names
    out_rows.setdefault(sn, {})[r["name"]] = e
out = ["DataEnv.slot.GX=DataEnv.slot.GX||{};GX.sub=GX.sub||{};", "/* fx data batch B18 (generated by tools/gen_subskills.py): skill proficiencies of subclass features, a fixed skill or one chosen from a list. Do not edit by hand. */", "(function(){", "var P=function(k,e){GX.sub[k]=(GX.sub[k]||[]).concat(e)};"]
for k in sorted(out_rows): out.append("P(%s,%s);" % (json.dumps(k, ensure_ascii=False), json.dumps(list(out_rows[k].values()), ensure_ascii=False)))
out.append("})();")
open(os.path.join(ROOT, "src", "data", "fx-B18-subskills2.js"), "w", encoding="utf8").write("\n".join(out) + "\n")
print(len(out_rows), "subclasses:", ", ".join(sorted(out_rows)))
