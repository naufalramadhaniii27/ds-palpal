"""Writes src/data/fx-B16-speciesimm.js: Immunity to disease (and the Advantage that the same sentence states) for species traits that no record carries.
Usage: python3 tools/gen_speciesimm.py <gate data cache .json>   (use a cache made before the output file exists)
Only sentences whose missing record is IMM, optionally with ADV, and that say immunity to disease. The Advantage row is the sentence itself, so its condition stays attached."""
import sys, json, re, datetime, os
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, os.path.join(ROOT, "tests"))
import clause_gate as g
D = json.load(open(sys.argv[1])); g.build_index(D)
bd = g.load_by_design(); al = g.load_allow()
feats, res, ctx = g.scan(D, bd, al, datetime.date.today().isoformat())
rows = {}
for r in res:
    if r["status"] != "uncovered" or r["kind"] != "species" or r.get("unexplained"): continue
    m0 = re.search(r"no record for ([A-Z,]+)", r["why"])
    need = set(m0.group(1).split(",")) if m0 else set()  # the classes still missing a record
    if not need or not need <= {"IMM", "ADV"} or "IMM" not in need: continue
    t = re.sub(r"^[-\s]+", "", r["text"].strip()).rstrip(".")
    if not re.search(r"immun(?:e|ity) to disease", t, re.I) or len(t) > 220: continue
    defs = [["Immunity", "Disease"]]
    if "ADV" in need and re.search(r"\bAdvantage\b", t): defs.append(["Advantage", "%s: %s" % (r["name"], t)])
    elif "ADV" in need: continue
    rows.setdefault(r["owner"], []).append({"n": r["name"] + " (immunity)", "defs": defs})
out = ["DataEnv.slot.GX=DataEnv.slot.GX||{};GX.species=GX.species||{};", "/* fx data batch B16 (generated by tools/gen_speciesimm.py): Immunity to disease of species traits, with the Advantage line of the same sentence. Do not edit by hand. */", "(function(){", "var P=function(k,e){GX.species[k]=(GX.species[k]||[]).concat(e)};"]
for k in sorted(rows): out.append("P(%s,%s);" % (json.dumps(k, ensure_ascii=False), json.dumps(rows[k], ensure_ascii=False)))
out.append("})();")
open(os.path.join(ROOT, "src", "data", "fx-B16-speciesimm.js"), "w", encoding="utf8").write("\n".join(out) + "\n")
print(len(rows), "species:", ", ".join(sorted(rows)))
