"""Writes src/data/fx-B12-itemriders.js: an atkDice note for item sentences that state an extra damage die on a weapon hit.
Usage: python3 tools/gen_itemriders.py <gate data cache .json>   (use a cache made before the output file exists)
The note is the item's own sentence (already own wording). Items that another fx file already names are skipped."""
import sys, json, re, datetime, os, glob
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, os.path.join(ROOT, "tests"))
import clause_gate as g
D = json.load(open(sys.argv[1])); g.build_index(D)
bd = g.load_by_design(); al = g.load_allow()
feats, res, ctx = g.scan(D, bd, al, datetime.date.today().isoformat())
FILES = {f: open(f, encoding="utf8").read() for f in glob.glob(os.path.join(ROOT, "src", "data", "fx-*.js")) if "fx-B12" not in f}
def has_dice(name):
    """True when another fx file already names this item, so its rows (notes, dice) already show."""
    q = json.dumps(name)
    return any(q in t for t in FILES.values())
XD = {r[0] for r in list(D["dmgi"]) + [x for v in D["wxi"].values() for x in v] if len(r) > 5 and (r[5] or {}).get("xd")}  # 12h already adds the row's own xd note
rows = {}
for r in res:
    if r["status"] != "uncovered" or r["kind"] != "item": continue
    t = r["text"].strip()
    m = re.search(r"extra (\d+d\d+) ([A-Za-z]+) damage", t, re.I)
    if not m or not re.search(r"\b(hit|hits|strike|attack)\b", t) or len(t) > 220 or "(" in r["name"]: continue
    if has_dice(r["name"]) or r["name"] in XD: continue
    note = re.sub(r"^[-\s]+", "", t).rstrip(".")
    rows.setdefault(r["name"], {})[m.group(1) + m.group(2)] = {"n": r["name"] + " (rider)", "atkDice": [{"when": r["name"], "d": m.group(1), "t": m.group(2).capitalize(), "note": note}]}
out = ["DataEnv.slot.GX=DataEnv.slot.GX||{};GX.item=GX.item||{};", "/* fx data batch B12 (generated by tools/gen_itemriders.py): extra damage dice of magic weapons, shown as a note on the weapon rows. Do not edit by hand. */", "(function(){", "var P=function(k,e){GX.item[k]=(GX.item[k]||[]).concat(e)};"]
for k in sorted(rows):
    out.append("P(%s,%s);" % (json.dumps(k, ensure_ascii=False), json.dumps(list(rows[k].values()), ensure_ascii=False)))
out.append("})();")
open(os.path.join(ROOT, "src", "data", "fx-B12-itemriders.js"), "w", encoding="utf8").write("\n".join(out) + "\n")
print(len(rows), "items")
