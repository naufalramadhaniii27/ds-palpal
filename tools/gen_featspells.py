"""Writes src/data/fx-B26-featspells.js: the cantrips and spells a feat teaches or keeps prepared by name, with the spellcasting ability the feat text states.
Usage: python3 tools/gen_featspells.py <gate data cache .json>   (use a cache made before the output file exists)
Readings: "the ability raised by this feat" (spCls @asi), "choose Intelligence, Wisdom or Charisma" (spCls @abpick with an ability pick), one fixed ability named in the text (spCls @sub:AB).
Skips a feat whose spells are level gated, whose text names two different abilities, or that another fx file already gives spells."""
import sys, json, re, os, glob
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
D = json.load(open(sys.argv[1]))
FX = "".join(open(f, encoding="utf8").read() for f in glob.glob(os.path.join(ROOT, "src", "data", "fx-*.js")) if "fx-B26" not in f)
SKIP = {"Arcane Overload"}  # the Crucible Storm Chaser background already gives Fire Bolt (tests/invariants.py dup-attack)
AB = {"Intelligence": "INT", "Wisdom": "WIS", "Charisma": "CHA", "Int": "INT", "Wis": "WIS", "Cha": "CHA"}
NAME = r"([A-Z][A-Za-z' ]+?)"
rows = {}
for n, f in D["feats"].items():
    t = f.get("full") or f.get("d") or ""
    if n in SKIP or re.search(r"character level \d|level \d+ (?:you|also)|At \d+(?:st|nd|rd|th) level", t): continue
    sp = re.findall(r"You (?:learn|know) the " + NAME + r" cantrip\b", t)
    sp += [x for x in re.findall(r"You (?:also )?always have the " + NAME + r" spell prepared|You (?:also )?always have " + NAME + r" prepared", t) for x in x if x]
    sp = [s for s in sp if s and s.lower() not in ("it", "them", "that spell")]
    if not sp or len(set(sp)) != len(sp): continue
    asi = bool(re.search(r"ability (?:raised|increased) by this feat", t))
    pick = bool(re.search(r"(?:[Cc]hoose|pick) Intelligence, Wisdom,? or Charisma as|(?:Int|Intelligence), (?:Wis|Wisdom),? or (?:Cha|Charisma) is your spellcasting ability", t))
    fixed = set(AB[x] for x in re.findall(r"\b(Intelligence|Wisdom|Charisma)\b(?: is your spellcasting ability|\.? )", t) if re.search(x + r" is (?:your|its) spellcasting ability|spellcasting ability (?:for [a-z ]+ )?is " + x + r"|cast with " + x + r"|using " + x, t))
    if asi + pick + (1 if fixed else 0) != 1: continue
    if len(fixed) > 1: continue
    q = re.escape(json.dumps(n))
    if re.search(q + r"[^\n]{0,400}spells\"?\s*:", FX) or re.search(r"\{n:" + q + r"[^\n]{0,300}spells", FX): continue
    e = {"n": n + " (spells)", "spells": [[1, ",".join(sp)]]}
    if asi: e["spCls"] = "@asi"
    elif pick:
        e["spCls"] = "@abpick"; e["pick"] = [{"k": "ab", "t": "multi", "n": 1, "title": "Spellcasting ability", "list": [["INT", ""], ["WIS", ""], ["CHA", ""]]}]
    else: e["spCls"] = "@sub:" + list(fixed)[0]
    rows[n] = e
out = ["DataEnv.slot.GX=DataEnv.slot.GX||{};GX.feat=GX.feat||{};", "/* fx data batch B26 (generated by tools/gen_featspells.py): the cantrips and spells a feat teaches or keeps prepared by name. Do not edit by hand. */", "(function(){", "var P=function(k,e){GX.feat[k]=(GX.feat[k]||[]).concat([e])};"]
for k in sorted(rows): out.append("P(%s,%s);" % (json.dumps(k, ensure_ascii=False), json.dumps(rows[k], ensure_ascii=False)))
out.append("})();")
open(os.path.join(ROOT, "src", "data", "fx-B26-featspells.js"), "w", encoding="utf8").write("\n".join(out) + "\n")
print(len(rows), "feats:", ", ".join(sorted(rows)))
