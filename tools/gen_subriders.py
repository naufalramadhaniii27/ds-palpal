"""Writes src/data/fx-B24-subriders.js: an atkDice note for subclass and feat sentences that state an extra damage die on a weapon or unarmed hit.
Usage: python3 tools/gen_subriders.py <gate data cache .json>   (use a cache made before the output file exists)
The note is the feature's own sentence (already own wording). Skips a feature when its level is not unique, when another fx file already names it, or when the sentence is about a spell, a save, or scales per level."""
import sys, json, re, datetime, os, glob
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, os.path.join(ROOT, "tests"))
import clause_gate as g
D = json.load(open(sys.argv[1])); g.build_index(D)
bd = g.load_by_design(); al = g.load_allow()
feats, res, ctx = g.scan(D, bd, al, datetime.date.today().isoformat())
ALLF = {f: open(f, encoding="utf8").read() for f in glob.glob(os.path.join(ROOT, "src", "data", "*.js")) if "fx-B24" not in f}
FXF = {f: t for f, t in ALLF.items() if os.path.basename(f).startswith("fx-")}
def levels(sub, feat):
    base = re.sub(r" \((?:2014|PSA|Deep Magic|Banneret)\)$", "", sub); lv = set()
    for f, t in ALLF.items():
        for m in re.finditer(r'"name":"' + re.escape(base) + '"', t):
            seg = t[m.end():m.end() + 40000]; n = seg.find('"name":"'); seg = seg[:n] if n > 0 else seg
            for h in re.finditer(r'\[(\d+),"' + re.escape(feat) + '"', seg): lv.add(int(h.group(1)))
    return lv
def named(owner, feat):
    q, f = json.dumps(owner), json.dumps(feat)
    return any(q in line and (("n:" + f) in line or ('"n":' + f) in line or ("," + f + ",") in line) for t in FXF.values() for line in t.split("\n"))
RX = re.compile(r"extra (\d+d\d+) ([A-Za-z]+) damage", re.I)
rows = {"sub": {}, "feat": {}}
for r in res:
    if r["status"] != "uncovered" or r["kind"] not in rows or "DMG" not in r["why"]: continue
    t = re.sub(r"^[-\s]+", "", r["text"].strip())
    m = RX.search(t)
    if not m or len(t) > 220 or not re.search(r"\b(hit|hits|strike|attack)\b", t): continue
    if re.search(r"\bspell|\bsave\b|saving throw|\bper\b|\bfor each\b|\beach (?:level|slot|charge)\b|\bslot|\bcantrip|\bbreath|\bcreature takes|\btarget takes|\bmust\b|\bexpend|\bspend|\bcharge", t, re.I): continue
    when = "unarmed" if re.search(r"unarmed", t, re.I) else "weapon"
    if r["kind"] == "sub":
        owner = r["owner"].split("/", 1)[1]; lv = levels(owner, r["name"])
        if len(lv) != 1: continue
    else:
        owner = r["name"]; lv = None
    if named(owner, r["name"]): continue
    e = {"n": r["name"] + " (rider)"}
    if lv: e["l"] = min(lv)
    e["atkDice"] = [{"when": when, "d": m.group(1), "t": m.group(2).capitalize(), "note": t.rstrip(".")}]
    rows[r["kind"]].setdefault(owner, {})[r["name"] + m.group(1)] = e
    mm = re.search(r"\((2d\d+) at level (\d+)\)|, (2d\d+) from level (\d+)", t)
    if mm and lv:
        d2 = mm.group(1) or mm.group(3); l2 = int(mm.group(2) or mm.group(4))
        rows[r["kind"]][owner][r["name"] + d2] = {"n": r["name"] + " (rider " + str(l2) + ")", "l": l2, "atkDice": [{"when": when, "d": str(int(d2.split("d")[0]) - int(m.group(1).split("d")[0])) + "d" + d2.split("d")[1], "t": m.group(2).capitalize(), "note": r["name"] + ", adds to the " + m.group(1) + " above for " + d2 + " in all"}]}  # the sheet adds atkDice rows, so this row is the increment
# hand correction (review g02): Polar Strikes becomes 1d6 at Ranger level 11 ("becomes" wording the regex skips)
if "Winter Walker" in rows["sub"]:
    rows["sub"]["Winter Walker"]["Frigid Explorer1d4"]["lMax"] = 10
    rows["sub"]["Winter Walker"]["Frigid Explorer1d6"] = {"n": "Frigid Explorer (rider 11)", "l": 11, "atkDice": [{"when": "weapon", "d": "1d6", "t": "Cold", "note": "Frigid Explorer, 1d6 in all"}]}
out = ["DataEnv.slot.GX=DataEnv.slot.GX||{};GX.sub=GX.sub||{};GX.feat=GX.feat||{};", "/* fx data batch B24 (generated by tools/gen_subriders.py): extra damage dice of subclass features and feats on a weapon or unarmed hit, shown as a note on the attack rows. Do not edit by hand. */", "(function(){", "var S=function(k,e){GX.sub[k]=(GX.sub[k]||[]).concat(e)};", "var F=function(k,e){GX.feat[k]=(GX.feat[k]||[]).concat(e)};"]
n = 0
for kind, fn in (("sub", "S"), ("feat", "F")):
    for k in sorted(rows[kind]):
        out.append("%s(%s,%s);" % (fn, json.dumps(k, ensure_ascii=False), json.dumps(list(rows[kind][k].values()), ensure_ascii=False))); n += len(rows[kind][k])
out.append("})();")
open(os.path.join(ROOT, "src", "data", "fx-B24-subriders.js"), "w", encoding="utf8").write("\n".join(out) + "\n")
print("wrote", n, "rows")
