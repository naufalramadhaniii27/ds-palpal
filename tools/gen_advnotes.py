"""Writes src/data/fx-B9-advnotes.js: Advantage and Disadvantage notes for feat and species sentences that state one plainly.
Usage: python3 tools/gen_advnotes.py <gate data cache .json made by tests/clause_gate.py --save-data>
Each note is the sentence itself (already own wording in the data), so its condition stays attached. Run again after the data changes; the output is deterministic."""
import sys, json, re, datetime, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tests"))
import clause_gate as g
D = json.load(open(sys.argv[1])); g.build_index(D)
bd = g.load_by_design(); al = g.load_allow()
feats, res, ctx = g.scan(D, bd, al, datetime.date.today().isoformat())
sp, ft = {}, {}
for r in res:
    if r["status"] != "uncovered" or r.get("unexplained") or r["kind"] not in ("feat", "species") or set(r["need"]) not in ({"ADV"}, {"DIS"}): continue
    t = r["text"].strip().rstrip(".")
    if len(t) > 170 or re.search(r"\d|Loading|long range|Long range", t): continue
    m = re.search(r"\b(Advantage|Disadvantage)\b", t)
    if not m: continue
    body = re.sub(r"^You (?:have|gain) ", "", t)
    row = [m.group(1), "%s: %s" % (r["name"], body[0].upper() + body[1:])]
    if r["kind"] == "species": sp.setdefault(r["owner"], []).append({"n": r["name"], "defs": [row]})
    else: ft.setdefault(r["owner"], []).append({"n": r["name"] + " (note)", "defs": [row]})
out = ["/* fx data batch B9 (generated by tools/gen_advnotes.py): Advantage and Disadvantage notes of feats and species. Do not edit by hand. */", "DataEnv.slot.GX=DataEnv.slot.GX||{};", "(function(){", "GX.species=GX.species||{};GX.feat=GX.feat||{};",
       "var P=function(t,k,e){t[k]=(t[k]||[]).concat(e)};"]
for k in sorted(sp): out.append("P(GX.species,%s,%s);" % (json.dumps(k), json.dumps(sp[k], ensure_ascii=False)))
for k in sorted(ft): out.append("P(GX.feat,%s,%s);" % (json.dumps(k), json.dumps(ft[k], ensure_ascii=False)))
out.append("})();")
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "data", "fx-B9-advnotes.js"), "w", encoding="utf8").write("\n".join(out) + "\n")
print(len(sp), "species,", len(ft), "feats")
