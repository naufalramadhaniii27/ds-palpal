#!/usr/bin/env python3
"""Cut a Codex icon grid into icons. python3 tools/art_grid.py SHEET.png LIST.txt [--cols 10]
LIST.txt: lines like '12. generic/artisan | artisan'. Generic ids go to img/icon/<group>/<slug>.avif, other ids to img/icon/<cat>/<slug>.avif.
Updates img/manifest.json and src/fx/23-class-art-data.js."""
import json, os, re, sys
from PIL import Image
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sheet, lst = sys.argv[1], sys.argv[2]
GAMMA = float(sys.argv[sys.argv.index("--gamma") + 1]) if "--gamma" in sys.argv else 1.0
cols = int(sys.argv[sys.argv.index("--cols") + 1]) if "--cols" in sys.argv else 10
BG = set("acolyte artisan charlatan criminal entertainer farmer guard guide hermit merchant noble sage sailor scribe soldier wayfarer".split())
def dest(i):
    cat, slug = i.split("/", 1)
    if cat != "generic": return cat, slug
    if slug in BG: return "background", slug
    if slug.startswith("size-"): return "size", slug[5:]
    if slug == "species-custom": return "species", "custom"
    if slug == "background-custom": return "background", "custom"
    if slug.startswith("cat-"): return "cat", slug[4:]
    return "species", slug
MAN = os.path.join(ROOT, "img", "manifest.json"); man = json.load(open(MAN)); man.setdefault("icon", {})
im = Image.open(sheet).convert("RGBA"); cw, ch = im.width // cols, im.height // cols
rows = [l for l in open(lst, encoding="utf-8") if re.match(r"^\d+\. ", l)]
n = 0
for l in rows:
    num = int(l.split(".")[0]) - 1; i = l.split(". ", 1)[1].split(" | ")[0].strip()
    r, c = divmod(num, cols); cell = im.crop((c * cw, r * ch, (c + 1) * cw, (r + 1) * ch)).resize((128, 128), Image.LANCZOS)
    cat, slug = dest(i); d = os.path.join(ROOT, "img", "icon", cat); os.makedirs(d, exist_ok=True)
    if cat != "size" and GAMMA != 1:  # lift brightness to match the older Codex icons (mean value 0.67)
        lut = [round(255 * (v / 255) ** GAMMA) for v in range(256)]; rgb = cell.convert("RGB").point(lut * 3); a = cell.getchannel("A"); cell = rgb.convert("RGBA"); cell.putalpha(a)
    if cat == "size":  # light silhouette, relative height kept but readable at 24 px
        H = {"tiny": .34, "small": .5, "medium": .66, "large": .8, "huge": .92, "gargantuan": 1.0}[slug]
        big = im.crop((c * cw, r * ch, (c + 1) * cw, (r + 1) * ch)); bb = big.getchannel("A").point(lambda v: 255 if v > 40 else 0).getbbox()
        sil = big.crop(bb); a = sil.getchannel("A"); t = round(128 * H); w = max(1, round(sil.width * t / sil.height))
        a = a.resize((w, t), Image.LANCZOS); fill = Image.new("RGBA", (w, t), (222, 205, 168, 255)); fill.putalpha(a)
        cell = Image.new("RGBA", (128, 128), (0, 0, 0, 0)); cell.alpha_composite(fill, ((128 - w) // 2, 128 - t - 2))
    cell.save(os.path.join(d, slug + ".avif"), "AVIF", quality=62, speed=6); n += 1
    s = man["icon"].setdefault(cat, [])
    if slug not in s: s.append(slug)
for k in man["icon"]: man["icon"][k] = sorted(man["icon"][k])
json.dump(man, open(MAN, "w"), indent=1, sort_keys=True)
open(os.path.join(ROOT, "src", "fx", "23-class-art-data.js"), "w").write("/* generated by tools/art_pipeline.py. Do not edit by hand */\nvar __ART=" + json.dumps(man, sort_keys=True, separators=(",", ":")) + ";\n")
print(n, "icons")
