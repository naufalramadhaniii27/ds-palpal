#!/usr/bin/env python3
"""Stage T1/T2: map entries to 5e.tools images and convert the matches to small WebP in data/img/ (served by Pages, loaded lazily by <img loading=lazy>).
  python3 tools/q/qimg.py [--check]
Writes tools/q/imgmap.json ({"monster": {"Name|SRC": "bestiary/SRC/Name"}, ...}), src/data/q11-img.js (window.QIMG name index for builder side categories) and reports/t-img.md (numbers)."""
import os, sys, json, re
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(os.path.dirname(HERE)); sys.path.insert(0, HERE)
import qlib, qmon
IMG = "/home/claude/5etools-mirror-3/5etools-img"
OUT = os.path.join(ROOT, "data", "img")
from PIL import Image
def avail(folder):
    d = os.path.join(IMG, folder); out = {}
    if not os.path.isdir(d): return out
    for src in os.listdir(d):
        p = os.path.join(d, src)
        if os.path.isdir(p):
            for f in os.listdir(p):
                if f.endswith(".webp"): out[(src, f[:-5])] = "%s/%s/%s" % (folder, src, f[:-5])
        elif src.endswith(".webp"): out[("", src[:-5])] = "%s/%s" % (folder, src[:-5])
    return out
def convert(rel, w, q, write):
    src = os.path.join(IMG, rel + ".webp"); dst = os.path.join(OUT, rel + ".webp")
    if not os.path.exists(src): return 0
    if write and not os.path.exists(dst):
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        im = Image.open(src); im.thumbnail((w, w * 2)); im.save(dst, "WEBP", quality=q, method=4)
    return os.path.getsize(dst) if os.path.exists(dst) else 0
PREF = ["XPHB", "XDMG", "XMM", "EFA", "PHB", "DMG", "MM"]
def main(write):
    rep = []; imap = {}; used = []
    # monsters: art first, token otherwise
    art = avail("bestiary"); tok = avail("bestiary/tokens")
    pairs, _ = qmon.rows(); m = {}; na = nt = nn = 0
    for src, x in pairs:
        k = (src, x["name"])
        if k in art: m["%s|%s" % (x["name"], src)] = art[k]; na += 1; used.append((art[k], 480, 70))
        elif k in tok: m["%s|%s" % (x["name"], src)] = tok[k] + "~t"; nt += 1; used.append((tok[k], 128, 72))
        else: nn += 1
    imap["monster"] = {k: v for k, v in m.items()}; rep.append(("monster", len(pairs), na, nt, nn))
    qidx = {}
    for folder, cat, names in (("items", "item", None), ("races", "species", None), ("classes", "class", None), ("backgrounds", "bg", None), ("spells", "spell", None), ("feats", "feat", None)):
        a = avail(folder); best = {}
        for (src, name), rel in a.items():
            if name not in best or (src in PREF and best[name][0] not in PREF): best[name] = (src, rel)
        qidx[cat] = {n: v[1] for n, v in best.items()}
        for n, v in best.items(): used.append((v[1], 480, 70))
        rep.append((cat, len(a), len(best), 0, 0))
    for folder, cat in (("deities", "deity"), ("vehicles", "vehicle"), ("objects", "object"), ("decks", "deck"), ("recipes", "recipe"), ("bastions", "facility")):
        a = avail(folder); mm = {}
        for (src, name), rel in a.items(): mm["%s|%s" % (name, src.upper() if src else "")] = rel; used.append((rel, 480, 70))
        imap[cat] = mm; rep.append((cat, len(a), len(a), 0, 0))
    total = 0
    for rel, w, q in used: total += convert(rel, w, q, write)
    rep.append(("converted files", len(used), total // 1024, 0, 0))
    print(rep)
    if write:
        json.dump(imap, open(os.path.join(HERE, "imgmap.json"), "w"), ensure_ascii=False)
        open(os.path.join(ROOT, "src", "data", "q11-img.js"), "w", encoding="utf-8").write("/* Generated by tools/q/qimg.py. Image paths under data/img/ by name. */\nwindow.QIMG=" + json.dumps(qidx, ensure_ascii=False, separators=(",", ":")) + ";\n")
        with open(os.path.join(ROOT, "reports", "t-img.md"), "w") as f:
            f.write("# T1 and T2: images\n\n| Category | Files in repo | Matched | Token only | No image |\n|---|---|---|---|---|\n" + "\n".join("| %s | %s | %s | %s | %s |" % r for r in rep) + "\n\nLast row: files converted and total KB.\n")
if __name__ == "__main__": main("--check" not in sys.argv)
