#!/usr/bin/env python3
"""Stage T4/T5: apply Codex art. Reads PNGs from a checkout of branch art-t4 (art/t4/<cat>/<slug>.png), converts them to WebP in data/img/codex/<cat>/<slug>.webp,
and adds them to tools/q/imgmap.json (QREFS categories, key Name|SRC) and src/data/q11-img.js (builder categories, key name). Names come from reports/codex/t4-wave-*.md.
  python3 tools/q/qart.py <path to art/t4>"""
import os, sys, re, json, glob
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(os.path.dirname(HERE))
from PIL import Image
def names():
    out = {}
    for f in glob.glob(os.path.join(ROOT, "reports", "codex", "t4-wave-*.md")):
        for m in re.finditer(r"save as art/t4/(\w+)/([^ \n]+)\.png\nSubject: [^\"]*\"([^\"]+)\"", open(f, encoding="utf-8").read()):
            out[(m.group(1), m.group(2))] = m.group(3)
    return out
def main(src):
    nm = names(); done = 0; miss = []
    imap = json.load(open(os.path.join(HERE, "imgmap.json"))); qj = os.path.join(ROOT, "src", "data", "q11-img.js")
    t = open(qj, encoding="utf-8").read(); qidx = json.loads(t[t.index("window.QIMG=") + 12: t.rindex(";")])
    for (cat, slug), name in nm.items():
        p = os.path.join(src, cat, slug + ".png")
        # 5etools image wins: skip when this name already has a non-Codex image in any source
        if cat in ("item", "feat"):
            if name in qidx.get(cat, {}) and not qidx[cat][name].startswith("codex/"): continue
        else:
            if any(k.startswith(name + "|") and not str(v).startswith("codex/") for k, v in imap.get(cat, {}).items()): continue
        if not os.path.exists(p): miss.append(slug); continue
        dst = os.path.join(ROOT, "data", "img", "codex", cat, slug + ".webp"); os.makedirs(os.path.dirname(dst), exist_ok=True)
        im = Image.open(p).convert("RGBA"); im.thumbnail((384, 384)); im.save(dst, "WEBP", quality=78, method=4)
        rel = "codex/%s/%s" % (cat, slug)
        if cat in ("item", "feat"): qidx.setdefault(cat, {})[name] = rel
        else: imap.setdefault(cat, {})["%s|*" % name] = rel
        done += 1
    json.dump(imap, open(os.path.join(HERE, "imgmap.json"), "w"), ensure_ascii=False)
    open(qj, "w", encoding="utf-8").write("/* Generated by tools/q/qimg.py and qart.py. */\nwindow.QIMG=" + json.dumps(qidx, ensure_ascii=False, separators=(",", ":")) + ";\n")
    print("applied", done, "missing", len(miss))
if __name__ == "__main__": main(sys.argv[1])
