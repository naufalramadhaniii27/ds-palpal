#!/usr/bin/env python3
"""Second image pass: Library entries with no picture that match a file in data/img by a looser name rule.
Input: a JSON list [[cat, name, image-or-empty]] of every Library entry (from tests/q_imgaudit.py --dump). Writes src/data/q19-img-more.js,
which adds to window.QIMG (path without data/img/ and .webp).   python3 tools/q/imgmore.py LIST.json"""
import json, os, re, sys, collections
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(os.path.dirname(HERE))
n = lambda s: re.sub(r"[^a-z0-9]", "", s.lower())
CLS = ["Barbarian", "Bard", "Cleric", "Druid", "Fighter", "Monk", "Paladin", "Ranger", "Rogue", "Sorcerer", "Warlock", "Wizard", "Artificer", "Psion", "Mystic"]
DIRS = {"item": ["items"], "gear": ["items"], "sub": ["classes"], "species": ["races"], "deity": ["deities"], "feat": ["feats"], "bg": ["backgrounds"], "facility": ["bastions"],
        "vehicle": ["vehicles"], "recipe": ["recipes"], "object": ["objects"], "creature": ["bestiary"], "charopt": ["charcreationoptions"],
        "disease": ["conditionsdiseases"], "hazard": ["hazards", "traps"], "language": ["languages"], "rule": ["variantrules", "conditionsdiseases"], "optfeat": ["optionalfeatures"], "opt": ["optionalfeatures"],
        "deck": ["decks"], "class": ["classes"], "spell": ["spells"], "psionic": ["optionalfeatures"]}
def keys(cat, base):
    """names a file could stand for"""
    out = {n(base)}
    b = re.sub(r"[\s_-]*\d+$", "", base).strip(); out.add(n(b))
    b2 = re.sub(r"\s*\((?:PHB|XPHB|DMG)\)$", "", b); out.add(n(b2))
    b3 = re.sub(r"^Symbol of ", "", b); out.add(n(b3))
    b4 = re.sub(r"\s+(Player Version|Map)$", "", b); out.add(n(b4))
    if cat == "sub":
        for c in CLS:
            if b.endswith(" " + c): out.add(n(b[:-len(c) - 1])); out.add(n(c + b[:-len(c)]))
    return {k for k in out if len(k) > 3}
PRE = re.compile(r"^(?:Path of the|Path of|Circle of the|Circle of|College of the|College of|Oath of the|Oath of|Way of the|Way of|Order of the|Order of|Domain of the|The|Undead|Primal Path of)\s+", re.I)
def libkeys(cat, name):
    out = {n(name)}
    anyp = r"[^)]*" if cat in ("sub", "deity", "gear", "item") else r"20\d\d|Monster|Legacy"
    b = re.sub(r"\s*\((?:%s)\)\s*$" % anyp, "", name).strip(); out.add(n(b))
    if cat in ("sub", "deity"):
        out.add(n(PRE.sub("", b)))
        out.add(n(re.sub(r"\s+(Domain|Patron|Oath|Circle|Path|Order|Tradition|Archetype|College|Way)$", "", PRE.sub("", b))))
    return {k for k in out if len(k) > 3}
def main():
    L = json.load(open(sys.argv[1]))
    used = {r[2] for r in L if r[2]}
    files = collections.defaultdict(list)
    for d in set(x for v in DIRS.values() for x in v):
        base = os.path.join(ROOT, "data", "img", d)
        if not os.path.isdir(base): continue
        for src in sorted(os.listdir(base)):
            for f in sorted(os.listdir(os.path.join(base, src))) if os.path.isdir(os.path.join(base, src)) else []:
                if f.endswith(".webp"):
                    rel = "%s/%s/%s" % (d, src, f[:-5])
                    if rel + ".webp" not in {u.replace("data/img/", "") for u in used} and "data/img/" + rel + ".webp" not in used: files[d].append(rel)
    out = collections.defaultdict(dict); seen = collections.Counter()
    have = {(c, n(x)): i for c, x, i in L if i}
    for cat, name, im in L:
        if im or cat not in DIRS: continue
        base = re.sub(r"\s*\([^)]*\)\s*$", "", name).strip()
        if base != name and (cat, n(base)) in have:  # the plain name has a picture: the variant shares it
            out[cat][name] = have[(cat, n(base))].replace("data/img/", "")[:-5]; seen[cat] += 1; continue
        lk = libkeys(cat, name)
        for d in DIRS[cat]:
            for rel in files[d]:
                fk = keys(cat, os.path.basename(rel))
                if cat in ("sub", "deity"): fk |= {n(PRE.sub("", x)) for x in [os.path.basename(rel)]} | {n(re.sub(r"\s+(Domain|Patron|Oath|Circle|Path|Order|Tradition|Archetype|College|Way)$", "", PRE.sub("", re.sub(r"\s+(%s)$" % "|".join(CLS), "", os.path.basename(rel)))))}
                if lk & fk and name not in out[cat]:
                    out[cat][name] = rel; seen[cat] += 1
    for cat, name, im in L:  # the 2024 class art replaces the 2014 one
        if cat == "class" and os.path.exists(os.path.join(ROOT, "data", "img", "classes", "XPHB", name + ".webp")): out["class"][name] = "classes/XPHB/" + name
    for cat in out: print(cat, len(out[cat]), list(out[cat].items())[:3])
    open(os.path.join(ROOT, "src", "data", "q19-img-more.js"), "w", encoding="utf-8").write("/* Generated by tools/q/imgmore.py. Image paths under data/img/ by name. */\nwindow.QIMG=window.QIMG||{};(function(){var M=" + json.dumps(out, ensure_ascii=False) + ';Object.keys(M).forEach(function(c){window.QIMG[c]=window.QIMG[c]||{};Object.keys(M[c]).forEach(function(k){window.QIMG[c][k]=M[c][k];});});})();\n')
main()
