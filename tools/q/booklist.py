#!/usr/bin/env python3
"""Books and adventures: title, date, author, level range and the chapter and section titles (names only, no text) -> src/data/q15-books.js.
So a search for "Cragmaw Hideout" finds Lost Mine of Phandelver. Facts only.   python3 tools/q/booklist.py   (Q0_DIR default /home/claude/work/q0)"""
import json, os, re
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(os.path.dirname(HERE)); Q0 = os.environ.get("Q0_DIR", "/home/claude/work/q0")
def ld(f): return json.load(open(os.path.join(Q0, f), encoding="utf-8"))
def hd(h): return h if isinstance(h, str) else h.get("header", "")
rows = []
for kind, key, f in (("Book", "book", "books.json"), ("Adventure", "adventure", "adventures.json")):
    for x in ld(f)[key]:
        chap = []
        for c in x.get("contents", []):
            o = c.get("ordinal"); lab = ("%s %s. " % (o.get("type", "part").title(), o["identifier"])) if o and "identifier" in o else ""
            hs = [hd(h) for h in c.get("headers", []) if hd(h)]
            chap.append("**%s%s.** %s" % (lab, c["name"], "; ".join(hs[:40]).replace("; ", ", ")) if hs else "**%s%s.**" % (lab, c["name"]))
        lv = x.get("level"); lvs = ("%s to %s" % (lv.get("start"), lv.get("end"))) if isinstance(lv, dict) else ""
        tl = [t for t in (["Kind", kind], ["Published", x.get("published", "")], ["Author", x.get("author", "")], ["Series", x.get("storyline", "")], ["Levels", lvs], ["Group", x.get("group", "")]) if t[1]]
        rows.append({"n": x["name"], "s": x["source"].lower(), "sub": "%s • %s" % (kind, x.get("published", "")[:4]), "tl": tl, "p": ["**Contents**"] + chap,
                     "tx": (x["name"] + " " + kind + " " + " ".join(chap)).lower().replace("**", "")})
open(os.path.join(ROOT, "src", "data", "q15-books.js"), "w", encoding="utf-8").write("/* Generated by tools/q/booklist.py from 5e.tools book and adventure lists. Titles only. Do not edit by hand. */\n(function(){\nvar ROWS=" + json.dumps(rows, ensure_ascii=False) + ';\nDataEnv.slot.QREFS=DataEnv.slot.QREFS||{};DataEnv.slot.QREFS["book"]=(DataEnv.slot.QREFS["book"]||[]).concat(ROWS);\n})();\n')
print(len(rows), "rows")
