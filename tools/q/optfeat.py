#!/usr/bin/env python3
"""Optional features (invocations, maneuvers, infusions, fighting styles, runes and more) from 5e.tools -> src/data/q14-optfeat.js.
Facts (type, prerequisite, level, book) come from the source. The description comes from tools/q/overlay/optfeat.json ({"Name|SRC": "own wording"}).
  python3 tools/q/optfeat.py --export OUT.json   list the entries that still need a description (name, source, types, prerequisite, source text)
  python3 tools/q/optfeat.py                     write src/data/q14-optfeat.js (needs Q0_DIR/optionalfeatures.json, default /home/claude/work/q0)"""
import json, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(os.path.dirname(HERE))
Q0 = os.environ.get("Q0_DIR", "/home/claude/work/q0")
TYPES = {"EI": "Eldritch Invocation", "MV:B": "Battle Master Maneuver", "MV": "Maneuver", "MV:C2-UA": "Cavalier Maneuver", "MM": "Metamagic", "ED": "Elemental Discipline", "AI": "Artificer Infusion",
         "AS": "Arcane Shot", "FS:F": "Fighting Style (Fighter)", "FS:R": "Fighting Style (Ranger)", "FS:P": "Fighting Style (Paladin)", "FS:B": "Fighting Style (Bard)", "PB": "Pact Boon",
         "RN": "Rune", "RP": "House Rank", "OTH": "Other", "OR": "Onomancy Resonant", "AF": "Alchemical Formula", "TT": "Traditional Tradition"}
SRC = {"PHB": "PHB 2014", "XPHB": "PHB 2024", "TCE": "Tasha's", "XGE": "Xanathar's", "EFA": "Eberron: Forge of the Artificer", "FRHoF": "Heroes of Faerun", "DMG": "DMG 2014", "XDMG": "DMG 2024"}
def tag(t): return re.sub(r"\{@\w+ ([^}|]*)[^}]*\}", r"\1", t)
def walk(e):
    if isinstance(e, str): return tag(e)
    if isinstance(e, list): return " ".join(walk(x) for x in e)
    if isinstance(e, dict):
        if e.get("type") == "table": return "Table: " + " | ".join(walk(r) for r in e.get("rows", [])[:12])
        return ((e.get("name") + ". ") if e.get("name") else "") + walk(e.get("entries") or e.get("items") or "")
    return ""
def prereq(x):
    out = []
    for p in x.get("prerequisite", []):
        if "level" in p:
            l = p["level"]; out.append(("%s level %s" % (l.get("class", {}).get("name", "character"), l.get("level"))) if isinstance(l, dict) else "Level %s" % l)
        if "spell" in p: out.append("Spell: " + ", ".join(tag(s).split("#")[0] for s in p["spell"]))
        if "pact" in p: out.append("Pact of the " + p["pact"])
        if "patron" in p: out.append("Patron: " + p["patron"])
        if "feature" in p: out.append(", ".join(tag(f) for f in p["feature"]))
        if "item" in p: out.append("Item: " + ", ".join(tag(i) for i in p["item"]))
        if "otherSummary" in p: out.append(tag(p["otherSummary"].get("entrySummary", "")))
    return "; ".join(o for o in out if o)
def pick():
    d = json.load(open(os.path.join(Q0, "optionalfeatures.json"), encoding="utf-8"))["optionalfeature"]
    have = set(open(os.path.join(ROOT, "tools", "q", "optnames.txt"), encoding="utf-8").read().split("\n")) if os.path.exists(os.path.join(ROOT, "tools", "q", "optnames.txt")) else set()
    by = {}
    for x in d:
        if x["name"] in have: continue
        old = by.get(x["name"])
        if old is None or x["source"] in ("XPHB", "XDMG") or (old["source"] not in ("XPHB", "XDMG") and x["source"] in ("TCE", "XGE")): by[x["name"]] = x
    return [by[k] for k in sorted(by)]
def main(a):
    rows = pick()
    if "--export" in a:
        json.dump([{"key": "%s|%s" % (x["name"], x["source"]), "types": [TYPES.get(t, t) for t in x.get("featureType", [])], "prerequisite": prereq(x), "source_text": walk(x.get("entries", []))} for x in rows],
                  open(a[a.index("--export") + 1], "w", encoding="utf-8"), ensure_ascii=False, indent=0); print(len(rows), "entries exported"); return 0
    ov = json.load(open(os.path.join(HERE, "overlay", "optfeat.json"), encoding="utf-8")) if os.path.exists(os.path.join(HERE, "overlay", "optfeat.json")) else {}
    out, miss = [], []
    for x in rows:
        k = "%s|%s" % (x["name"], x["source"]); t = ov.get(k)
        if not t: miss.append(k); continue
        ty = ", ".join(TYPES.get(q, q) for q in x.get("featureType", [])); pr = prereq(x)
        out.append({"n": x["name"], "s": "core" if x["source"] in ("XPHB", "XDMG") else x["source"].lower(), "sub": "Optional Feature • " + ty + " • " + SRC.get(x["source"], x["source"]),
                    "tl": [t2 for t2 in (["Type", ty], ["Prerequisite", pr], ["Book", SRC.get(x["source"], x["source"])]) if t2[1]], "p": [t], "tx": (x["name"] + " " + ty + " " + pr + " " + t).lower()})
    open(os.path.join(ROOT, "src", "data", "q14-optfeat.js"), "w", encoding="utf-8").write("/* Generated by tools/q/optfeat.py from 5e.tools facts. Own wording. Do not edit by hand. */\n(function(){\nvar ROWS=" + json.dumps(out, ensure_ascii=False) + ';\nDataEnv.slot.QREFS=DataEnv.slot.QREFS||{};DataEnv.slot.QREFS["optfeat"]=(DataEnv.slot.QREFS["optfeat"]||[]).concat(ROWS);\n})();\n')
    print(len(out), "rows written,", len(miss), "without a description", miss[:5]); return 0
sys.exit(main(sys.argv[1:]))
