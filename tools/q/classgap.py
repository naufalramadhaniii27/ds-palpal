#!/usr/bin/env python3
"""Class and subclass features that 5e.tools lists and the Library lacked (mostly 2014 and Unearthed Arcana classes). Own wording.
Texts come from tools/q/overlay/classgap.json (key "Name|Class or Subclass|SRC").
  python3 tools/q/classgap.py --export OUT.json     entries that need text
  python3 tools/q/classgap.py                       writes src/data/q17-class-gap.js (QREFS["feature"])
Needs Q0_DIR with class/*.json and tools/q/classhave.txt (feature names already in the app)."""
import json, os, re, sys, glob
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import qlib
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(os.path.dirname(HERE))
norm = lambda s: re.sub(r"[^a-z0-9]", "", s.lower())
HAVE = {norm(l) for l in open(os.path.join(HERE, "classhave.txt"), encoding="utf-8").read().split("\n") if l}
OP = os.path.join(HERE, "overlay", "classgap.json"); OV = json.load(open(OP, encoding="utf-8")) if os.path.exists(OP) else {}
def todo():
    out = []; seen = set()
    for p in sorted(glob.glob(os.path.join(qlib.Q0, "class", "class-*.json"))):
        j = json.load(open(p, encoding="utf-8"))
        for kind, ck in (("classFeature", "className"), ("subclassFeature", "subclassShortName")):
            for x in j.get(kind, []):
                n = x["name"]
                if norm(n) in HAVE: continue
                owner = x[ck] if kind == "classFeature" else x.get("subclassShortName", "")
                parent = x["className"]
                k = "%s|%s|%s" % (n, owner, x["source"].upper())
                if k in seen: continue
                seen.add(k)
                out.append({"key": k, "n": n, "owner": owner, "cls": parent, "src": x["source"], "lvl": x.get("level"), "sub": kind == "subclassFeature", "text": qlib.walk(x.get("entries", []))})
    return out
def main():
    rows = todo()
    if len(sys.argv) > 2 and sys.argv[1] == "--export":
        need = [{"key": e["key"], "source_text": e["text"][:1800]} for e in rows if e["text"].strip() and not OV.get(e["key"])]
        json.dump(need, open(sys.argv[2], "w", encoding="utf-8"), ensure_ascii=False, indent=1); print(len(need), "need text of", len(rows)); return
    out = []; nod = 0
    for e in rows:
        d = OV.get(e["key"])
        if not d: nod += 1; continue
        tl = [["Class", e["cls"]]] + ([["Subclass", e["owner"]]] if e["sub"] else []) + ([["Level", str(e["lvl"])]] if e["lvl"] else [])
        sub = "Subclass feature" if e["sub"] else "Class feature"
        out.append({"n": e["n"], "s": qlib.srcid(e["src"]), "sub": sub, "tl": tl, "p": [d], "tx": (e["n"] + " " + sub + " " + e["cls"] + " " + e["owner"] + " " + d).lower()})
    open(os.path.join(ROOT, "src", "data", "q17-class-gap.js"), "w", encoding="utf-8").write("/* Generated by tools/q/classgap.py. Own wording. Do not edit by hand. */\n(function(){\nvar ROWS=" + json.dumps(out, ensure_ascii=False) + ';\nwindow.QREFS=window.QREFS||{};window.QREFS["feature"]=(window.QREFS["feature"]||[]).concat(ROWS);\n})();\n')
    print(len(out), "rows,", nod, "skipped (no text)")
main()
