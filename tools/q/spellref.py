#!/usr/bin/env python3
"""Cross references of every spell (classes, subclasses, species, backgrounds, feats, other options) from 5etools gendata-spell-source-lookup.json.
python3 tools/q/spellref.py /path/to/5etools-src/data   ->  src/data/q21-spellref.js  (DataEnv.slot.SPREF)"""
import json, os, sys, glob
D = sys.argv[1]; ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
L = json.load(open(os.path.join(D, "generated", "gendata-spell-source-lookup.json"), encoding="utf-8"))
SRC = {"XPHB": "PHB'24", "XDMG": "DMG'24", "XMM": "MM'25", "PHB": "PHB'14", "DMG": "DMG'14", "MM": "MM'14", "UtHftLH": "UHftLH", "UHftLH": "UHftLH"}
sn = lambda c: SRC.get(c, c)
# spell facts from the spell files
facts = {}
for f in glob.glob(os.path.join(D, "spells", "spells-*.json")):
    for s in json.load(open(f, encoding="utf-8")).get("spell", []):
        k = s["name"].lower(); cur = facts.get(k)
        if cur and cur["src"] == "XPHB": continue
        facts[k] = {"src": s["source"], "pg": s.get("page"), "srd": bool(s.get("srd52")), "br": bool(s.get("basicRules2024")), "ref": s.get("referenceSources", []), "al": s.get("alias", [])}
out = {}
def add(e, grp, item):
    g = e.setdefault(grp, []); 
    if item not in g: g.append(item)
for src, spells in L.items():
    for name, v in spells.items():
        e = out.setdefault(name, {})
        for cs, cls in v.get("class", {}).items():
            for c in cls: add(e, "c", [c, cs])
        for cs, byc in v.get("classVariant", {}).items():
            for c in byc: add(e, "c", [c, cs])
        for cs, byc in v.get("subclass", {}).items():
            for c, bysrc in byc.items():
                for ss, subs in bysrc.items():
                    for sk, sv in subs.items(): add(e, "s", [sv.get("name", sk), c, ss, sk])
        for bs, bgs in v.get("background", {}).items():
            for b in bgs: add(e, "b", [b, bs])
        for fs, fts in v.get("feat", {}).items():
            for ft in fts: add(e, "f", [ft, fs])
        for os_, ofs in v.get("optionalfeature", {}).items():
            for of, ov in ofs.items(): add(e, "o", [of, os_, (ov.get("featureType") or [""])[0]])
        for rs, rcs in v.get("race", {}).items():
            for r, rv in rcs.items(): add(e, "r", [r, rs, (rv.get("baseName") if isinstance(rv, dict) else "") or ""])
for k, e in out.items():
    f = facts.get(k)
    if f: e["m"] = {"s": sn(f["src"]), "p": f["pg"], "srd": 1 if f["srd"] else 0, "br": 1 if f["br"] else 0, "ref": [sn(x) for x in f["ref"]]}
for k, f in facts.items():
    if k not in out and (f["srd"] or f["br"] or f["ref"]): out[k] = {"m": {"s": sn(f["src"]), "p": f["pg"], "srd": 1 if f["srd"] else 0, "br": 1 if f["br"] else 0, "ref": [sn(x) for x in f["ref"]]}}
for k, f in facts.items():  # aliases such as Firebolt
    for a in f["al"]:
        if a.lower() not in out and k in out: out[a.lower()] = out[k]
js = "DataEnv.declare(\"SPREF\");\n/* Generated by tools/q/spellref.py from 5etools gendata-spell-source-lookup. Cross references of every spell. */\nDataEnv.slot.SPREF=" + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n"
open(os.path.join(ROOT, "src", "data", "q21-spellref.js"), "w", encoding="utf-8").write(js)
print(len(out), len(js) // 1024, "KB")
