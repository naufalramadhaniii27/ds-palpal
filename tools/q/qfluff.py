"""Stage S: lore (fluff) for species, backgrounds, classes, subclasses. Source: 5e.tools fluff files. Text comes from overlays tools/q/overlay/fluff_*.py (F = {"kind|Name": "text"}), own wording.
  python3 tools/q/qfluff.py todo <chunk> <of>     list entries for agents
  python3 tools/q/qfluff.py count"""
import sys, os, json, re
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import qlib
PREF = ["XPHB", "EFA", "XDMG", "XMM", "PHB"]
def entries():
    out = {}
    def add(kind, arr):
        for e in arr:
            t = qlib.walk(e.get("entries", []))
            if len(t.split()) < 8: continue
            k = "%s|%s" % (kind, e["name"])
            if k not in out or (e["source"] in PREF and out[k]["source"] not in PREF): out[k] = {"key": k, "kind": kind, "name": e["name"], "source": e["source"], "text": t}
    add("species", qlib.load("fluff-races.json")["raceFluff"]); add("bg", qlib.load("fluff-backgrounds.json")["backgroundFluff"])
    d = qlib.load("fluff-class.json"); add("class", d["classFluff"]); add("sub", d["subclassFluff"])
    return list(out.values())
if __name__ == "__main__" and len(sys.argv) > 1 and sys.argv[1] != "build":
    es = entries()
    if sys.argv[1] == "count": print(len(es)); print(sum(len(e["text"].split()) for e in es))
    else:
        i, n = int(sys.argv[2]), int(sys.argv[3]); size = -(-len(es) // n)
        for e in es[(i - 1) * size: i * size]:
            print("## %s" % e["key"]); print("source:", e["source"]); print(e["text"][:1500]); print()

def build(write=True):
    import glob, importlib.util
    F = {}
    for p in sorted(glob.glob(os.path.join(HERE, "overlay", "fluff_*.py"))):
        sp = importlib.util.spec_from_file_location(os.path.basename(p)[:-3], p); m = importlib.util.module_from_spec(sp)
        try: sp.loader.exec_module(m)
        except SyntaxError: print("not readable yet", p); continue
        F.update(getattr(m, "F", {}))
    out = {"species": {}, "bg": {}, "class": {}, "sub": {}}; gap = []
    for e in entries():
        t = F.get(e["key"])
        if not t: gap.append(e["key"]); continue
        out[e["kind"]][e["name"]] = t
    for k in F:
        if k not in {e["key"] for e in entries()}: gap.append("overlay without entry: " + k)
    js = "DataEnv.declare(\"FLUFF\");\n/* Generated by tools/q/qfluff.py. Lore in own words. */\nDataEnv.slot.FLUFF=" + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n"
    if write: open(os.path.join(os.path.dirname(os.path.dirname(HERE)), "src", "data", "q10-fluff.js"), "w", encoding="utf-8").write(js)
    print("lore entries", sum(len(v) for v in out.values()), "gap", len(gap), gap[:5])
if __name__ == "__main__" and len(sys.argv) > 1 and sys.argv[1] == "build": build()
