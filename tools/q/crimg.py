#!/usr/bin/env python3
"""Creature name -> picture path under data/img/ (src/data/q12-crimg.js, window.CRIMG). Art is preferred, a token is used when a creature has only a token.
Run from the repo root after the bestiary folder or data/tg-creatures.json changed:  python3 tools/q/crimg.py"""
import json, os
B = "data/img/bestiary"
art, tok = {}, {}
for src in sorted(os.listdir(B)):
    p = os.path.join(B, src)
    if src == "tokens":
        for s2 in sorted(os.listdir(p)):
            for f in os.listdir(os.path.join(p, s2)):
                if f.endswith(".webp"): tok.setdefault(f[:-5], {})[s2] = "bestiary/tokens/%s/%s" % (s2, f[:-5])
    elif os.path.isdir(p):
        for f in os.listdir(p):
            if f.endswith(".webp"): art.setdefault(f[:-5], {})[src] = "bestiary/%s/%s" % (src, f[:-5])
out = {}
for c in json.load(open("data/tg-creatures.json", encoding="utf-8"))["creatures"]:
    for pool in (art, tok):
        h = pool.get(c["n"])
        if h: out[c["n"]] = h.get(c["src"]) or h[sorted(h)[0]]; break
with open("src/data/q12-crimg.js", "w", encoding="utf-8") as f:
    f.write("/* Generated by tools/q/crimg.py. Creature picture paths under data/img/ by name. */\nwindow.CRIMG=" + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(len(out), "creatures with a picture,", sum("/tokens/" in v for v in out.values()), "of them a token")
