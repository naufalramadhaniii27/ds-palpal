#!/usr/bin/env python3
"""Life tables (trinkets, why a class, why a background) as Library rows in category "table". Lines are in own wording:
tools/q/life_out.json (same shape as the 5e.tools life.json lists). Writes src/data/q18-life.js.   python3 tools/q/life.py"""
import json, os, re
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(os.path.dirname(HERE))
L = json.load(open(os.path.join(HERE, "overlay", "life_out.json"), encoding="utf-8"))
tag = lambda t: re.sub(r"\{@\w+ ([^|}]*)[^}]*\}", r"\1", t)
def num(i, n): return ("%02d" % (i + 1)) if n < 100 else ("%02d" % (i + 1) if i < 99 else "00")
def row(name, sub, lines, roll):
    p = ["**%s.** %s" % (num(i, len(lines)), tag(t)) for i, t in enumerate(lines)]
    return {"n": name, "s": "phb14", "sub": sub, "tl": [["Roll", roll]], "p": p, "tx": (name + " " + sub + " table life backstory " + " ".join(p)).lower().replace("**", "")}
rows = [row("Trinkets", "Table • Trinkets", L["trinkets"], "d100")]
for k, v in L["class"].items(): rows.append(row("Why I Became a " + k.split("|")[0], "Table • Class backstory", v, "d%d" % len(v)))
for k, v in L["background"].items(): rows.append(row("Why I Chose the %s Background" % k.split("|")[0], "Table • Background backstory", v, "d%d" % len(v)))
open(os.path.join(ROOT, "src", "data", "q18-life.js"), "w", encoding="utf-8").write("/* Generated by tools/q/life.py. Own wording. Do not edit by hand. */\n(function(){\nvar ROWS=" + json.dumps(rows, ensure_ascii=False) + ';\nwindow.QREFS=window.QREFS||{};window.QREFS["table"]=(window.QREFS["table"]||[]).concat(ROWS);\n})();\n')
print(len(rows), "rows")
