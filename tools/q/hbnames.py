#!/usr/bin/env python3
"""Writes src/data/q20-hbnames.js: the name and type of every homebrew row, so the Library can find them without the source being on.
The full rows stay in data/hb/<id>.json and load when an entry is opened. Run from the repo root."""
import json, glob, os, re
idx = open("src/data/q09-hbindex.js", encoding="utf-8").read()
m = re.search(r"var L=(\[.*?\]);", idx, re.S)
src = json.loads(m.group(1))
pos = {q["id"]: i for i, q in enumerate(src)}
rows, n = [], 0
for q in src:
    f = "data/hb/%s.json" % q["id"]
    if not os.path.exists(f): continue
    for r in json.load(open(f, encoding="utf-8")):
        rows.append([pos[q["id"]], r["n"], r.get("sub", "")]); n += 1
out = "DataEnv.declare(\"HBN\");\n/* Generated by tools/q/hbnames.py. Name and type of every homebrew row. Full rows load from data/hb/<id>.json. */\nDataEnv.slot.HBN=" + json.dumps(rows, ensure_ascii=False, separators=(",", ":")) + ";\n"
open("src/data/q20-hbnames.js", "w", encoding="utf-8").write(out)
print(n, "rows", len(out) // 1024, "KB")
