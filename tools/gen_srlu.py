"""Writes src/data/fx-B29-srlu.js: the use pool of a feature that can also be refilled by spending a spell slot (srLu = lowest slot level; the card shows a Restore button).
Usage: python3 tools/gen_srlu.py <gate data cache .json>   (use a cache made before the output file exists)
Takes uncovered sentences of the form 'spend a level N (or higher) spell slot ... restore/regain/again' whose owner feature already has a use pool."""
import sys, json, re, datetime, os
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, os.path.join(ROOT, "tests"))
import clause_gate as g
D = json.load(open(sys.argv[1])); g.build_index(D)
bd = g.load_by_design(); al = g.load_allow()
feats, res, ctx = g.scan(D, bd, al, datetime.date.today().isoformat())
LU = {}
for x in D["lu"]: LU.setdefault((x.get("owner"), x.get("feature")), []).append(x)
RX = re.compile(r"(?:expend|spend)\w*\s+(?:a |an )?(?:spell slot of |slot of )?(?:level\s+)?(\d)(?:st|nd|rd|th)?(?:\+| level or higher|-level or higher| or higher)?\s*(?:level )?(?:spell )?slot[^.]{0,80}?(?:restor|regain|again|recover)|(?:restor|regain|recover)[^.]{0,60}(?:expend|spend)\w*\s+(?:a |an )?(?:level\s+)?(\d)", re.I)
RX2 = re.compile(r"(?:restor|regain|recover)\w*\s+(?:your use of it|use of it|one use|a use)[^.]{0,60}\b(?:level )?(\d)\+?(?:st|nd|rd|th)? ?(?:level )?(?:or higher )?(?:spell )?slot|\bagain by spending a level (\d) spell slot", re.I)
rows = {}
for r in res:
    if r["status"] != "uncovered" or r["kind"] != "sub" or "SLOT" not in r["why"]: continue
    t = r["text"]; m = RX.search(t) or RX2.search(t)
    if not m: continue
    lvl = int([x for x in m.groups() if x][0])
    owner = r["owner"].split("/", 1)[1]
    lus = LU.get((owner, r["name"])) or []
    if not lus: continue
    lv = min(x.get("lvl", 1) for x in lus)
    rows.setdefault(owner, {})[r["name"]] = {"n": r["name"], "l": lv, "srLu": lvl}
out = ["DataEnv.slot.GX=DataEnv.slot.GX||{};GX.sub=GX.sub||{};", "/* Generated by tools/gen_srlu.py. Do not edit by hand. A pool that can be refilled by spending a spell slot. */", "(function(){", "var S=function(k,e){GX.sub[k]=(GX.sub[k]||[]).concat(e)};"]
n = 0
for owner in sorted(rows):
    es = list(rows[owner].values()); n += len(es)
    out.append("S(%s,%s);" % (json.dumps(owner), json.dumps(es)))
out.append("})();")
open(os.path.join(ROOT, "src", "data", "fx-B29-srlu.js"), "w", encoding="utf8").write("\n".join(out) + "\n")
print(n, "rows,", len(rows), "owners")
