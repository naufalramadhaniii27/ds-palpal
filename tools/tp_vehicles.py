"""Ships and ship upgrades of a third-party book as Library rows (QREFS.vehicle), same row shape as tools/q/qgen.py.
Ship rows hold facts only: numbers, names, weapon attack lines. Upgrade texts come from an overlay (own wording). Used by tp_build.py for books with "vehicles"."""
import re, json
from tp_monsters import clean, attack


def _flat(ents):
    out = []
    for e in ents or []:
        if isinstance(e, str): out.append(e)
        elif isinstance(e, dict): out.extend(_flat(e.get("entries", [])))
    return out


def _stats(v):
    st = {}
    for blk in v.get("other", []):
        if blk["name"] == "Ship Stats":
            for g in blk["entries"]:
                for e in g.get("entries", []):
                    if isinstance(e, dict): st[e["name"]] = clean(" ".join(_flat(e["entries"])))
    return st


def _names(v, title):
    out = []
    for blk in v.get("other", []):
        if blk["name"] == title:
            for g in blk["entries"]:
                for e in g.get("entries", []):
                    if isinstance(e, dict) and e.get("name"):
                        a = attack(e.get("entries", []))
                        out.append("**%s.**%s" % (clean(e["name"]), (" " + a) if a else ""))
    return out


def ship_row(v, skey):
    st = _stats(v)
    tl = [["Size", clean(v.get("size", ""))], ["Terrain", ", ".join(v.get("terrain", []))]]
    for lab, k in (("AC", "Armor Class"), ("Mega HP", "Mega Hit Points"), ("Shield Points", "Shield Points"), ("Engines", "Engines"), ("Systems", "Systems"), ("Crew", "Crew"), ("Cargo", "Cargo"), ("Cost", "Cost"), ("Challenge", "Challenge")):
        if st.get(k): tl.append([lab, st[k]])
    p = []
    for title in ("Traits", "Weapons"):
        b = _names(v, title)
        if b: p += ["**%s**" % title] + b
    return {"n": v["name"], "s": skey, "sub": "Ship • %s" % clean(v.get("size", "")), "tl": tl, "p": p, "tx": ("%s ship %s" % (v["name"], clean(v.get("size", "")))).lower(), "im": ""}


def upgrade_row(u, skey, text):
    cost = ""
    for e in u.get("entries", []):
        if isinstance(e, dict) and e.get("name") == "Cost": cost = clean(" ".join(_flat(e["entries"])))
    return {"n": u["name"], "s": skey, "sub": "Vehicle Upgrade • %s" % ", ".join(u.get("upgradeType", [])),
            "tl": [["Type", ", ".join(u.get("upgradeType", []))], ["Cost", cost]], "p": [text], "tx": ("%s vehicle upgrade %s" % (u["name"], text)).lower(), "im": ""}


def vehicle_file(ships, upgrades, skey, label, texts):
    rows = [ship_row(v, skey) for v in ships] + [upgrade_row(u, skey, texts.get(u["name"], "")) for u in upgrades]
    return ("/* Generated by tools/tp_vehicles.py from %s. Ship facts only, upgrade texts in own words. Do not edit by hand. */\n(function(){\nvar ROWS=%s;\n"
            "DataEnv.slot.QREFS=DataEnv.slot.QREFS||{};DataEnv.slot.QREFS[\"vehicle\"]=(DataEnv.slot.QREFS[\"vehicle\"]||[]).concat(ROWS);\n})();\n") % (label, json.dumps(rows, ensure_ascii=False))
