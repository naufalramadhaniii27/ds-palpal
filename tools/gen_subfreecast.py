"""Writes src/data/fx-B27-subfreecast.js: a spell that a subclass feature lets you cast once without a slot. The spell (always prepared) is always written; the once-per-Long-Rest use pool is added only when no use-pool row exists for the feature.
Usage: python3 tools/gen_subfreecast.py <gate data cache .json>   (use a cache made before the output file exists)
Skips a feature when its level is not unique, when another fx file when the sentence names more than one spell, or when the spell is not in the spell list."""
import sys, json, re, datetime, os, glob
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, os.path.join(ROOT, "tests"))
import clause_gate as g
D = json.load(open(sys.argv[1])); g.build_index(D)
bd = g.load_by_design(); al = g.load_allow()
feats, res, ctx = g.scan(D, bd, al, datetime.date.today().isoformat())
ALLF = {f: open(f, encoding="utf8").read() for f in glob.glob(os.path.join(ROOT, "src", "data", "*.js")) if "fx-B27" not in f}
FXF = {f: t for f, t in ALLF.items() if os.path.basename(f).startswith("fx-")}
SPELLS = {k.lower(): k for k in D["spellFull"]}
LUOWN = set((x.get("owner"), x.get("feature")) for x in D["lu"])
def levels(sub, feat):
    base = re.sub(r" \((?:2014|PSA|Deep Magic|Banneret)\)$", "", sub); lv = set()
    for f, t in ALLF.items():
        for m in re.finditer(r'"name":"' + re.escape(base) + '"', t):
            seg = t[m.end():m.end() + 40000]; n = seg.find('"name":"'); seg = seg[:n] if n > 0 else seg
            for h in re.finditer(r'\[(\d+),"' + re.escape(feat) + '"', seg): lv.add(int(h.group(1)))
    return lv
def named(owner, feat):
    q, f = json.dumps(owner), json.dumps(feat)
    return any(q in line and (("n:" + f) in line or ('"n":' + f) in line or ("," + f + ",") in line) for t in FXF.values() for line in t.split("\n"))
AB = {"Intelligence": "INT", "Wisdom": "WIS", "Charisma": "CHA"}
RX = re.compile(r"^You (?:can )?(?:also )?(?:cast ([A-Za-z' ]+?)(?: on yourself only)?(?: once)? (?:with no|without (?:a|using a|spending a)) (?:spell )?slot|always have ([A-Za-z' ]+?) prepared and can cast it once (?:without a slot|with no slot))(?:,? (?:using|with) (Intelligence|Wisdom|Charisma))?(?:,? (?:regain\w* (?:that|it|the use) (?:after|on) a Long Rest|without (?:a )?spell components|without components))?\.?$", re.I)
RX2 = re.compile(r"^You (?:also )?(?:learn|know|gain) (?:the )?([A-Za-z' ]+?) cantrip(?:, (?:using|cast with) (Intelligence|Wisdom|Charisma))?\.?$", re.I)
CASTERS = {"Bard", "Cleric", "Druid", "Sorcerer", "Warlock", "Wizard", "Artificer"}
rows = {}
for r in res:
    if r["status"] != "uncovered" or r["kind"] != "sub" or "SPELL" not in r["why"]: continue
    txt = re.sub(r"^[-\s]+", "", r["text"].strip())
    m2 = RX2.match(txt)
    if m2 and SPELLS.get(m2.group(1).strip().lower()):
        owner = r["owner"].split("/", 1)[1]; lv = levels(owner, r["name"])
        if len(lv) != 1 or named(owner, r["name"]): continue
        if not m2.group(2) and r["owner"].split("/", 1)[0] not in CASTERS: continue
        e1 = {"n": r["name"] + " (cantrip)", "l": min(lv), "spells": [[min(lv), SPELLS[m2.group(1).strip().lower()]]]}
        if m2.group(2): e1["spCls"] = "@sub:" + AB[m2.group(2).title()]
        rows.setdefault(owner, {})[r["name"]] = [e1]
        continue
    m = RX.match(txt)
    if not m: continue
    nm = (m.group(1) or m.group(2)).strip()
    if re.search(r"\b(?:or|and|each|one)\b", nm, re.I): continue
    sp = SPELLS.get(nm.lower())
    if not sp: continue
    owner = r["owner"].split("/", 1)[1]; lv = levels(owner, r["name"])
    if len(lv) != 1 or named(owner, r["name"]): continue
    haspool = (owner, r["name"]) in LUOWN or (r["owner"], r["name"]) in LUOWN
    if not m.group(3) and r["owner"].split("/", 1)[0] not in CASTERS: continue  # a non-caster class has no spellcasting ability to cast with
    e1 = {"n": r["name"] + " (spell)", "l": min(lv), "spells": [[min(lv), sp]]}
    if m.group(3): e1["spCls"] = "@sub:" + AB[m.group(3).title()]
    e2 = {"n": r["name"] + " (free cast)", "l": min(lv), "lu": {"n": r["name"] + ": " + sp + " without a slot", "max": 1, "reset": "long"}}
    rows.setdefault(owner, {})[r["name"]] = [e1] if haspool else [e1, e2]
out = ["DataEnv.slot.GX=DataEnv.slot.GX||{};GX.sub=GX.sub||{};", "/* fx data batch B27 (generated by tools/gen_subfreecast.py): a spell a subclass feature lets you cast once without a slot, with a once per Long Rest use pool. Do not edit by hand. */", "(function(){", "var S=function(k,e){GX.sub[k]=(GX.sub[k]||[]).concat(e)};"]
n = 0
for k in sorted(rows):
    out.append("S(%s,%s);" % (json.dumps(k, ensure_ascii=False), json.dumps([e for v in rows[k].values() for e in v], ensure_ascii=False))); n += len(rows[k])
out.append("})();")
open(os.path.join(ROOT, "src", "data", "fx-B27-subfreecast.js"), "w", encoding="utf8").write("\n".join(out) + "\n")
print("wrote", n, "features")
