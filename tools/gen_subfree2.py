"""Writes src/data/fx-B36-subfree2.js: spells that subclass features of non-spellcasting classes (or with a stated ability) let you cast without a slot. Only the features in CURATED are written (each read by hand); the use pool is added only when no pool of that feature exists.
Usage: python3 tools/gen_subfree2.py <gate data cache .json>   (use a cache made before the output file exists)"""
import sys, json, re, os, glob
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
D = json.load(open(sys.argv[1]))
ALLF = {f: open(f, encoding="utf8").read() for f in glob.glob(os.path.join(ROOT, "src", "data", "*.js")) if "fx-B36" not in f}
SPELLS = {k.lower(): k for k in D["spellFull"]}
LUOWN = set((x.get("owner"), x.get("feature")) for x in D["lu"])
def levels(sub, feat):
    base = re.sub(r" \((?:2014|PSA|Deep Magic|Banneret)\)$", "", sub); lv = set()
    for f, t in ALLF.items():
        for m in re.finditer(r'"name":"' + re.escape(base) + '"', t):
            seg = t[m.end():m.end() + 40000]; n = seg.find('"name":"'); seg = seg[:n] if n > 0 else seg
            for h in re.finditer(r'\[(\d+),"' + re.escape(feat) + '"', seg): lv.add(int(h.group(1)))
    return lv
# owner, feature, spells, spell ability (None: the class ability), pool (max, reset) or None for no pool
CURATED = [
 ("Danseur Macabre", "Dance with the Dead", ["Speak with Dead"], "CHA", (1, "long")),
 ("Mime", "Invisible Wall", ["Wall of Force"], "CHA", (1, "long")),
 ("Phantom", "Voice of Death", ["Speak with Dead"], "DEX", (1, "short")),
 ("Fey Ballerina", "Misty Waltz", ["Misty Step"], "CHA", ("mod:CHA", "short1")),
 ("Green Reaper", "Poison Control", ["Protection from Poison"], "WIS", ("mod:WIS", "long")),
 ("Temporal Trickster", "Stop The Clock", ["Time Stop"], "INT", (1, "long")),
 ("Circle of the Obelisk", "Transient Awakening", ["Speak with Animals", "Speak with Plants"], None, None),
 ("Mirrorkin", "Perfect Duplicate", ["Disguise Self", "Mirror Image"], None, None),
 ("Wasteland Strider", "Dimensional Step", ["Dimension Door"], None, ("pb", "long")),
 ("Imaskarcanist", "Secrets of Deep Imaskar", ["Glyph of Warding"], None, (1, "long")),
 ("Dynamo Engineer", "Spectrum Analyzer", ["Detect Magic"], None, None),
 ("Alchemist", "Chemical Mastery", ["Tasha's Bubbling Cauldron"], None, None),
 ("Cartographer", "Superior Atlas", ["Find the Path"], None, None),
 ("Path of the Spiritual Guardian", "Consult the Spirits", ["Augury", "Clairvoyance"], "WIS", None),
 ("Feylost", "Misty Pathways", ["Misty Step"], None, None),
 ("Holy Icon", "Raise Cohort", ["Raise Dead"], None, None),
 ("Star-Spangled Banner", "Patriotism", ["Heroism"], None, None),
]
LVL = {("Alchemist", "Chemical Mastery"): 15, ("Cartographer", "Superior Atlas"): 15}  # features whose level the data lists in the efa file only
rows = {}
for owner, feat, sps, ab, pool in CURATED:
    lv = levels(owner, feat) or ({LVL[(owner, feat)]} if (owner, feat) in LVL else set())
    if len(lv) != 1: print("skip level", owner, feat, lv); continue
    l = min(lv); names = [SPELLS.get(s.lower()) for s in sps]
    if not all(names): print("skip spell", owner, feat, names); continue
    e = {"n": feat + " (spell)", "l": l, "spells": [[l, ",".join(names)]]}
    if ab: e["spCls"] = "@sub:" + ab
    es = [e]
    if pool and (owner, feat) not in LUOWN:
        es.append({"n": feat + " (free cast)", "l": l, "lu": {"n": feat + ": " + ", ".join(names) + " without a slot", "max": pool[0], "reset": pool[1]}})
    rows.setdefault(owner, []).extend(es)
out = ["DataEnv.slot.GX=DataEnv.slot.GX||{};GX.sub=GX.sub||{};", "/* fx data batch B36 (generated by tools/gen_subfree2.py): spells a subclass feature lets you cast without a slot, with the use counter where the text gives one. Do not edit by hand. */", "(function(){", "var S=function(k,e){GX.sub[k]=(GX.sub[k]||[]).concat(e)};"]
for o in sorted(rows): out.append("S(%s,%s);" % (json.dumps(o, ensure_ascii=False), json.dumps(rows[o], ensure_ascii=False)))
out.append("})();")
open(os.path.join(ROOT, "src", "data", "fx-B36-subfree2.js"), "w", encoding="utf8").write("\n".join(out) + "\n")
print(sum(len(v) for v in rows.values()), "entries,", len(rows), "owners")
