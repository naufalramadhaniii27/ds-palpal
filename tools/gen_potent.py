"""Writes src/data/fx-B35-potent.js: 'Potent Spellcasting' of Cleric domains (the Wisdom modifier is added to the damage of Cleric cantrips) as an attack bonus on the cantrip rows.
Usage: python3 tools/gen_potent.py <gate data cache .json>   (use a cache made before the output file exists)"""
import sys, json, re, datetime, os, glob
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, os.path.join(ROOT, "tests"))
import clause_gate as g
D = json.load(open(sys.argv[1])); g.build_index(D)
bd = g.load_by_design(); al = g.load_allow()
feats, res, ctx = g.scan(D, bd, al, datetime.date.today().isoformat())
ALLF = {f: open(f, encoding="utf8").read() for f in glob.glob(os.path.join(ROOT, "src", "data", "*.js")) if "fx-B35" not in f}
def levels(sub, feat):
    base = re.sub(r" \((?:2014|PSA|Deep Magic|Banneret|DM14|ToH)\)$", "", sub); lv = set()
    for f, t in ALLF.items():
        for m in re.finditer(r'"name":"' + re.escape(base) + '"', t):
            seg = t[m.end():m.end() + 40000]; n = seg.find('"name":"'); seg = seg[:n] if n > 0 else seg
            for h in re.finditer(r'\[(\d+),"' + re.escape(feat) + '"', seg): lv.add(int(h.group(1)))
    return lv
def has_potent(owner):
    """another fx file already gives this domain its Potent Spellcasting (fx-L10: Grave Domain (2014), Peace Domain): a second row would add Wisdom twice"""
    rx = re.compile(r'(?:add|S)\("' + re.escape(owner) + r'",\[[^\n]*Potent Spellcasting')
    return any(rx.search(t) for f, t in ALLF.items() if os.path.basename(f).startswith("fx-"))
RX = re.compile(r"^(?:You )?add(?:ing)? your Wisdom modifier to the damage (?:you deal with )?(?:of )?(?:any |all )?(?:Cleric|cleric) cantrips?(?: you cast)?\.?$", re.I)
rows = {}
for r in res:
    if r["status"] != "uncovered" or r["kind"] != "sub" or r["name"] != "Potent Spellcasting": continue
    t = re.sub(r"^[-\s]+", "", r["text"].strip())
    if not (RX.match(t) or re.match(r"^Add your Wisdom modifier to the damage of cleric cantrips\.?$", t, re.I)): continue
    owner = r["owner"].split("/", 1)[1]
    if has_potent(owner): print("skip, has Potent Spellcasting", owner); continue
    lv = levels(owner, "Potent Spellcasting")
    if not lv and re.search(r"\((?:2014|PSA|DM14|ToH)\)$", owner): lv = {8}  # the 2014 domains give Potent Spellcasting at Cleric level 8 (listed as [8,"Potent Spellcasting",...] in the 2014 subclass files)
    if len(lv) != 1: print("skip level", owner, lv); continue
    rows[owner] = {"n": "Potent Spellcasting (cantrip damage)", "l": min(lv), "atkBonus": [{"when": "spell", "dmg": "WIS", "note": "Potent Spellcasting: Wisdom modifier added to Cleric cantrip damage."}]}
out = ["DataEnv.slot.GX=DataEnv.slot.GX||{};GX.sub=GX.sub||{};", "/* fx data batch B35 (generated by tools/gen_potent.py): Potent Spellcasting of Cleric domains adds the Wisdom modifier to Cleric cantrip damage. Do not edit by hand. */", "(function(){", "var S=function(k,e){GX.sub[k]=(GX.sub[k]||[]).concat(e)};"]
for o in sorted(rows): out.append("S(%s,[%s]);" % (json.dumps(o, ensure_ascii=False), json.dumps(rows[o], ensure_ascii=False)))
out.append("})();")
open(os.path.join(ROOT, "src", "data", "fx-B35-potent.js"), "w", encoding="utf8").write("\n".join(out) + "\n")
print(len(rows), "domains")
