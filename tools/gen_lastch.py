#!/usr/bin/env python3
"""Builds src/data/item-lastcharge.js: the last-charge roll of charged items (roll a d20 when the last charge is spent).
Reads the page data (window.__bldData) and writes one short own-wording note per item. python3 tools/gen_lastch.py [--print]"""
import json, re, sys, os
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
P = re.compile(r"(?:last|final) charge[^.]*\.?[^.]{0,40}roll (?:a )?(?:1d20|d20)|expend[^.]*last[^.]*roll (?:a )?(?:1d20|d20)", re.I)
TAIL = re.compile(r"roll (?:a )?(?:1d20|d20)[:,]?\s*(.{0,260})", re.I)
def outcome(tail):
    t = tail.lower()
    if "nonmagical" in t: return "it becomes a nonmagical item (the item text says what it keeps)"
    if re.search(r"keeps? its|retains? its|loses all (?:its )?other", t): return "it loses its other properties (the item text says what it keeps)"
    return "it is destroyed"
def note_for(name, text):
    t = re.sub(r"\s+", " ", text); m = TAIL.search(t)
    if not m: return None
    tail = m.group(1)
    if name == "Staff of the Magi": return "Last charge spent: roll 1d20. On a 20, it regains 1d12 + 1 charges."
    if name == "Staff of Fate": return "Last charge spent: roll 1d20. On a 9 or lower, it becomes a nonmagical quarterstaff that breaks on its first damaging hit."
    k = re.search(r"\b(?:on|if)\b[^.]{0,30}?\b(\d{1,2})\b", tail, re.I)
    n = k.group(1) if k else "1"
    return "Last charge spent: roll 1d20. On a %s, %s." % (n, outcome(tail))
def main():
    from playwright.sync_api import sync_playwright
    with sync_playwright() as p:
        b = p.chromium.launch(); pg = b.new_page(); pg.set_default_timeout(180000)
        pg.goto("file://" + os.path.join(ROOT, "index.html")); pg.wait_for_timeout(800)
        pg.evaluate("window.__bldNeed&&window.__bldNeed()"); pg.wait_for_function("window.__bldData", timeout=90000)
        d = pg.evaluate("window.__bldData()"); b.close()
    rows = list(d["dmgi"])
    for bk in d["wxi"].values(): rows += bk
    out = {}
    for r in rows:
        if len(r) > 5 and isinstance(r[4], str) and isinstance(r[5], dict) and r[5].get("ch") and P.search(r[4]) and not (isinstance(r[5]["ch"], list) and len(r[5]["ch"]) > 3):
            n = note_for(r[0], r[4])
            if n: out.setdefault(r[0], n)
    if "--print" in sys.argv:
        for k, v in sorted(out.items()): print(k, "|", v)
        print(len(out)); return
    body = 'DataEnv.declare("LASTCH");\n/* Last-charge roll of charged items. Generated by tools/gen_lastch.py, own wording. window.LASTCH[item] is added to the charges tracker of the item. */\n(function(){\n var W=DataEnv.slot;W.LASTCH=W.LASTCH||{};\n Object.assign(W.LASTCH,' + json.dumps(out, ensure_ascii=False, indent=1, sort_keys=True) + ');\n})();\n'
    open(os.path.join(ROOT, "src", "data", "item-lastcharge.js"), "w", encoding="utf-8").write(body)
    print("wrote", len(out))
if __name__ == "__main__": main()
