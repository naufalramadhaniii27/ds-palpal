#!/usr/bin/env python3
"""More Codex art, installed only where it has a place in the app and no 5etools picture. python3 tools/art_misc.py CODEX_BATCH_DIR HAS5.json [--dry]
CODEX_BATCH_DIR is art/batch of the Codex branch (needs portraits, emblems/subclass/extra, scenes/species). Updates img/ and the manifest."""
import json, os, sys
from PIL import Image
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC, H5 = sys.argv[1], json.load(open(sys.argv[2])); DRY = "--dry" in sys.argv
MAN = os.path.join(ROOT, "img", "manifest.json"); man = json.load(open(MAN)); tot = 0; log = {}
def avg(im): return "#%02x%02x%02x" % im.convert("RGB").resize((1, 1), Image.LANCZOS).getpixel((0, 0))
# portraits: a picker lists them all, no 5etools equivalent
d = os.path.join(SRC, "portraits"); have = set(man.get("portrait", [])); new = []
for f in sorted(os.listdir(d)):
    if f.endswith(".png") and f[:-4] not in have: new.append(f[:-4])
for k in new:
    if DRY: continue
    os.makedirs(os.path.join(ROOT, "img", "portrait"), exist_ok=True); dst = os.path.join(ROOT, "img", "portrait", k + ".avif")
    im = Image.open(os.path.join(d, k + ".png")).convert("RGB"); im.thumbnail((384, 480), Image.LANCZOS); im.save(dst, "AVIF", quality=60, speed=6); tot += os.path.getsize(dst)
man["portrait"] = sorted(have | set(new)) if not DRY else man.get("portrait", []); log["portraits"] = len(new)
# subclass emblems of other books: the id is class-subclass
CL = lambda s: "sorcerer" if s in ("aberrant-mind", "clockwork-soul", "draconic-bloodline") else "fighter" if s == "arcane-archer" else "druid" if s.startswith("circle-of-") else "bard" if s.startswith("college-of-") else "paladin" if s.startswith("oath-of-") else None
d = os.path.join(SRC, "emblems", "subclass", "extra"); have = set(man.get("esub", [])); new = []
for f in sorted(os.listdir(d)):
    if not f.endswith(".png"): continue
    s = f[:-4]; c = CL(s)
    if not c or s not in H5["sub"] or H5["sub"][s] or c + "-" + s in have: continue
    new.append((c + "-" + s, f))
for k, f in new:
    if DRY: continue
    os.makedirs(os.path.join(ROOT, "img", "emblem", "sub"), exist_ok=True); dst = os.path.join(ROOT, "img", "emblem", "sub", k + ".avif")
    im = Image.open(os.path.join(d, f)).convert("RGBA"); im.thumbnail((256, 256), Image.LANCZOS); im.save(dst, "AVIF", quality=60, speed=6); tot += os.path.getsize(dst)
if not DRY: man["esub"] = sorted(have | {k for k, _ in new})
log["subclass emblems"] = len(new)
# species scenes (builder cards): only species without a 5etools picture
d = os.path.join(SRC, "scenes", "species"); have = set(man.get("scn", {}).get("species", {})); new = []
for f in sorted(os.listdir(d)):
    if not f.endswith("-pc.png"): continue
    s = f[:-7]
    if s in have or s not in H5["species"] or H5["species"][s] or not os.path.exists(os.path.join(d, s + "-phone.png")): continue
    new.append(s)
for s in new:
    if DRY: continue
    os.makedirs(os.path.join(ROOT, "img", "scn", "species"), exist_ok=True); e = man.setdefault("scn", {}).setdefault("species", {}).setdefault(s, {})
    for kind, w in (("pc", 2400), ("phone", 1088)):
        im = Image.open(os.path.join(d, "%s-%s.png" % (s, kind))).convert("RGB")
        if im.width > w: im = im.resize((w, round(im.height * w / im.width)), Image.LANCZOS)
        dst = os.path.join(ROOT, "img", "scn", "species", "%s-%s.avif" % (s, kind)); im.save(dst, "AVIF", quality=54, speed=6); tot += os.path.getsize(dst)
        e[kind] = "img/scn/species/%s-%s.avif" % (s, kind); e["c"] = avg(im)
log["species scenes"] = len(new)
print(log, tot // 1024, "KB")
if not DRY:
    json.dump(man, open(MAN, "w"), indent=1, sort_keys=True)
    open(os.path.join(ROOT, "src", "fx", "23-class-art-data.js"), "w").write("/* generated by tools/art_pipeline.py. Do not edit by hand */\nwindow.__ART=" + json.dumps(man, sort_keys=True, separators=(",", ":")) + ";\n")
