"""Writes src/data/fx-B25-subprof.js: saving throw, tool and weapon proficiencies that a subclass feature or a feat states plainly: one fixed saving throw, one named tool set, Martial weapons.
Usage: python3 tools/gen_subprof.py <gate data cache .json>   (use a cache made before the output file exists)
The note is the feature's own sentence (already own wording). Skips a feature when its level is not unique, when another fx file already names it, or when the sentence has a choice, a condition or other numbers."""
import sys, json, re, datetime, os, glob
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, os.path.join(ROOT, "tests"))
import clause_gate as g
D = json.load(open(sys.argv[1])); g.build_index(D)
bd = g.load_by_design(); al = g.load_allow()
feats, res, ctx = g.scan(D, bd, al, datetime.date.today().isoformat())
ALLF = {f: open(f, encoding="utf8").read() for f in glob.glob(os.path.join(ROOT, "src", "data", "*.js")) if "fx-B25" not in f}
FXF = {f: t for f, t in ALLF.items() if os.path.basename(f).startswith("fx-")}
def levels(sub, feat):
    base = re.sub(r" \((?:2014|PSA|Deep Magic|Banneret)\)$", "", sub); lv = set()
    for f, t in ALLF.items():
        for m in re.finditer(r'"name":"' + re.escape(base) + '"', t):
            seg = t[m.end():m.end() + 40000]; n = seg.find('"name":"'); seg = seg[:n] if n > 0 else seg
            for h in re.finditer(r'\[(\d+),"' + re.escape(feat) + '"', seg): lv.add(int(h.group(1)))
    return lv
def named(owner, feat):
    q, f = json.dumps(owner), json.dumps(feat)
    return any(q in line and (("n:" + f) in line or ('"n":' + f) in line or ("," + f + ",") in line) for t in FXF.values() for line in t.split("\n"))
AB = {"Strength": "STR", "Dexterity": "DEX", "Constitution": "CON", "Intelligence": "INT", "Wisdom": "WIS", "Charisma": "CHA"}
RX_SAVE = re.compile(r"^(?:You )?(?:also )?(?:gain|become|are) proficien(?:t|cy) (?:in|with) (Strength|Dexterity|Constitution|Intelligence|Wisdom|Charisma) (?:saving throws|saves)\.?$", re.I)
RX_TOOL = re.compile(r"^(?:You )?(?:also )?(?:gain|become|are) proficien(?:t|cy) (?:in|with) ((?:[A-Z][A-Za-z']+ ){0,2}(?:Supplies|Tools|Kit|Utensils)|[A-Za-z' ]+(?:supplies|tools|kit|utensils))\.?$")
RX_WPN = re.compile(r"^(?:You )?(?:also )?(?:gain|become|are) proficien(?:t|cy) (?:in|with) Martial weapons\.?$", re.I)
rows = {"sub": {}, "feat": {}}
for r in res:
    if r["status"] != "uncovered" or r["kind"] not in rows or "PROF" not in r["why"]: continue
    t = re.sub(r"^[-\s]+", "", r["text"].strip())
    if re.search(r"\d|\bor\b|choice|\bif\b|\bdouble|\bexpertise", t, re.I): continue
    e = None
    m = RX_SAVE.match(t)
    if m: e = {"saveProf": [AB[m.group(1).title()]]}
    else:
        m = RX_TOOL.match(t)
        if m and not re.search(r"\b(?:your|any|all|one|that|them|it)\b", m.group(1), re.I):
            name = m.group(1).strip(); e = {"tools": [name[0].upper() + name[1:]]}
        elif RX_WPN.match(t): e = {"weapons": ["Martial"]}
    if not e: continue
    if r["kind"] == "sub":
        owner = r["owner"].split("/", 1)[1]; lv = levels(owner, r["name"])
        if len(lv) != 1: continue
        e["l"] = min(lv)
    else:
        owner = r["name"]
    if named(owner, r["name"]): continue
    e = dict({"n": r["name"] + " (proficiency)"}, **e)
    rows[r["kind"]].setdefault(owner, {})[r["name"]] = e
out = ["DataEnv.slot.GX=DataEnv.slot.GX||{};GX.sub=GX.sub||{};GX.feat=GX.feat||{};", "/* fx data batch B25 (generated by tools/gen_subprof.py): saving throw, tool and weapon proficiencies of subclass features and feats, stated plainly. Do not edit by hand. */", "(function(){", "var S=function(k,e){GX.sub[k]=(GX.sub[k]||[]).concat(e)};", "var F=function(k,e){GX.feat[k]=(GX.feat[k]||[]).concat([e])};"]
n = 0
for k in sorted(rows["sub"]):
    out.append("S(%s,%s);" % (json.dumps(k, ensure_ascii=False), json.dumps(list(rows["sub"][k].values()), ensure_ascii=False))); n += len(rows["sub"][k])
for k in sorted(rows["feat"]):
    for e in rows["feat"][k].values(): out.append("F(%s,%s);" % (json.dumps(k, ensure_ascii=False), json.dumps(e, ensure_ascii=False))); n += 1
out.append("})();")
open(os.path.join(ROOT, "src", "data", "fx-B25-subprof.js"), "w", encoding="utf8").write("\n".join(out) + "\n")
print("wrote", n, "rows")
